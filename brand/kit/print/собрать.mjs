/**
 * Сборка печати и документов Fixli: проверка, витрина, PDF в типографию и PNG в мессенджер.
 *
 * Зачем три выхода, если есть один источник:
 *  • PDF — то, что уходит в типографию и в офисный принтер. Формат страницы
 *    равен формату изделия, у визитки — с вылетом 3 мм;
 *  • PNG — то, что уходит в WhatsApp: подрядчик и заказчик смотрят с телефона;
 *  • `макеты.html` — витрина для нас: все шестнадцать листов рядом, с
 *    пояснением, откуда взялась каждая. Витрина СОБИРАЕТСЯ, руками не правится.
 *    Правится `документы.mjs`.
 *
 * ── Что проверяется ПЕРЕД экспортом ──────────────────────────────────────
 * Пятнадцать правил. Первые четыре — общие для носителей бренда, остальные
 * появились из-за того, что бумага живёт дольше рекламы, а счёт ещё и
 * подписывают:
 *
 *  1. литерал цвета в CSS — значение живёт один раз, в `brand/tokens.css`;
 *  2. физическое свойство вместо логического — половина листов набирается
 *     справа налево;
 *  3. обещания: каждый ключ `data-обещание` есть в `реестр-обещаний.md` и не
 *     помечен там красным;
 *  4. стоп-слова в отрисованном тексте — страхование, гарантия, 24/7, скидка,
 *     хранение вещей, капс FIXLI, некупленные домены и любой email;
 *  5. формат листа: отрисованный размер совпадает с объявленным в `ФОРМАТЫ`.
 *     Ошибка в миллиметрах здесь стоит тиража, а не перезагрузки страницы;
 *  6. знак не растянут: рамка каждого <img> держит пропорцию файла;
 *  7. знак нужного размера: внутри `fixli-знак.svg` есть поля (содержимое
 *     414,3 × 179,8 в рамке 436 × 198), поэтому картинка рисует знак на 5 %
 *     мельче рамки. Атрибут `data-знак` объявляет ширину САМОГО знака в мм и
 *     сверяется с расчётной — то же правило, что поймало знак на 10 % мельче
 *     заявленного на борту фургона;
 *  8. знак не мельче печатного минимума 16 мм по ширине (брендбук, раздел 01);
 *  9. безопасное поле: ни один текст не подходит к линии реза ближе 3 мм.
 *     На визитке линия реза проходит в 3 мм от края листа — то есть текст не
 *     ближе 6 мм от кромки PDF;
 * 10. печатный наряд слово в слово с телеграмным: честные состояния «время не
 *     назначено» и «адрес не записан» читаются из `job-message.ts` и ищутся в
 *     словаре. Два разных наряда на одну смену — это работник, приехавший не
 *     туда;
 * 11. в ивритских листах телефон и суммы помечены `dir="ltr"` — и этот атрибут
 *     стоит на строчном элементе, а не на блочном: на блочном он переключает
 *     ещё и выравнивание. Иначе номер
 *     разворачивается, а `4 648 ₪` читается как `₪ 648 4`;
 * 12. локаль не протекла: в ивритском листе нет кириллицы, в русском нет
 *     иврита кроме терминов из белого списка. Правило появилось последним и
 *     по делу — одиннадцать предыдущих дали зелёный на смете, где количество
 *     стояло по-русски: «3 чел. × 6 ч» в документе для израильтянина;
 * 13. формат ГОТОВОГО PDF, а не отрисованного листа: между ними стоит
 *     конвертер Chromium со своим округлением, и в типографию уезжает его
 *     результат, а не наш замер;
 * 14. пример заполнения в смете сходится со ставкой из прайса проекта:
 *     `packages/quote/src/data/pricing.ts`. Прайс уже переписывался целой
 *     фазой, и документ, показывающий старую ставку, врёт убедительнее сайта;
 * 15. лист набран Rubik, а не подстановкой. Шрифт лежит рядом файлом,
 *     подключён относительным путём и молча заменяется системным, если папка
 *     переедет. Проверяется замером ширины, а не document.fonts.check: тот
 *     дважды соврал — см. комментарий у самого правила.
 *
 * Запуск: node brand/kit/print/собрать.mjs [папка]
 */
import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { chromium } from '@playwright/test';

import { ДОКУМЕНТЫ, СЛОВАРЬ, ФОРМАТЫ } from './документы.mjs';

const ЗДЕСЬ = dirname(fileURLToPath(import.meta.url));
const КОРЕНЬ = join(ЗДЕСЬ, '..', '..', '..');
const выход = process.argv[2] ?? ЗДЕСЬ;

/* Содержимое внутри `fixli-знак.svg`: 414,3 × 179,8 при рамке 436 × 198. */
const ДОЛЯ_ЗНАКА = 414.3 / 436;
/** Минимальный печатный размер знака по ширине — брендбук, раздел 01. */
const ЗНАК_МИНИМУМ_ММ = 16;
/** Безопасное поле от линии реза. */
const БЕЗОПАСНОЕ_ПОЛЕ_ММ = 3;
/** Допуск на округления браузера при переводе мм в пиксели. */
const ДОПУСК_ММ = 0.6;
const ПИКСЕЛЕЙ_В_ММ = 96 / 25.4;

const беды = [];
const беда = (правило, текст) => беды.push(`${правило}: ${текст}`);

/* ═══ 1–2. Статические правила по CSS ═════════════════════════════════════ */

const css = readFileSync(join(ЗДЕСЬ, 'печать.css'), 'utf8');
/* Тела комментариев затираются: документ имеет право объяснять правило, называя
 * то, что запрещено. Переводы строк сохраняются, номера строк не съезжают. */
const cssБезКомментариев = css.replace(/\/\*[\s\S]*?\*\//g, (кусок) =>
  кусок.replace(/[^\n]/g, ' '),
);

for (const [i, строка] of cssБезКомментариев.split('\n').entries()) {
  const цвет = строка.match(/#[0-9a-fA-F]{3,8}\b|\brgba?\(|\bhsla?\(/);
  if (цвет) беда('литерал цвета', `печать.css:${i + 1} — ${цвет[0]}. Значение живёт в tokens.css`);

  const физическое = строка.match(
    /\b(margin|padding|border)-(left|right)\b|^\s*(left|right)\s*:|text-align:\s*(left|right)\b/,
  );
  if (физическое)
    беда('физическое свойство', `печать.css:${i + 1} — ${физическое[0].trim()}. Листы идут и справа налево`);
}

/* ═══ 3. Реестр обещаний ══════════════════════════════════════════════════ */

const реестр = readFileSync(join(ЗДЕСЬ, 'реестр-обещаний.md'), 'utf8');
const статусПоКлючу = new Map();
let текущийСтатус = null;
for (const строка of реестр.split('\n')) {
  if (/^##\s*✅/.test(строка)) текущийСтатус = '✅';
  else if (/^##\s*🟡/.test(строка)) текущийСтатус = '🟡';
  else if (/^##\s*🔴/.test(строка)) текущийСтатус = '🔴';
  else if (/^##\s/.test(строка)) текущийСтатус = null;

  const ключ = строка.match(/^\|\s*`([^`]+)`\s*\|/);
  if (ключ && текущийСтатус) статусПоКлючу.set(ключ[1], текущийСтатус);
}

if (статусПоКлючу.size === 0) беда('реестр', 'не разобран ни один ключ — сломался формат таблиц');

/* ═══ Разметка листа и страницы ═══════════════════════════════════════════ */

const шапкаСтраницы = (заголовок, стили) => `<!doctype html>
<html lang="ru">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <meta name="robots" content="noindex, nofollow" />
    <title>${заголовок}</title>
    <link rel="stylesheet" href="../../tokens.css" />
    <link rel="stylesheet" href="печать.css" />
    ${стили}
  </head>`;

function разметкаЛиста(док, локаль) {
  const с = СЛОВАРЬ[локаль];
  return `<article class="лист лист--${док.формат}" lang="${с.язык}" dir="${с.направление}"
         data-документ="${док.ключ}" data-локаль="${локаль}" data-формат="${док.формат}">
${док.лист(с)}
      </article>`;
}

/** Отдельная страница под один лист: из неё печатается PDF и снимается PNG. */
function страницаЛиста(док, локаль) {
  const ф = ФОРМАТЫ[док.формат];
  const стили = `<style>
      @page { size: ${ф.ширина}mm ${ф.высота}mm; margin: 0; }
      body { margin: 0; padding: 0; background: var(--fx-white); }
      .лист { box-shadow: none; }
    </style>`;
  return `${шапкаСтраницы(`${док.имя} · ${локаль}`, стили)}
  <body>
${разметкаЛиста(док, локаль)}
  </body>
</html>`;
}

/* ═══ Витрина ═════════════════════════════════════════════════════════════ */

function витрина() {
  const стили = `<style>
      /* Лист в витрине показывается уменьшенным: A4 в натуральную величину не
         помещается ни в один экран. Масштаб только для показа — PDF и PNG
         снимаются с отдельной страницы, где лист в натуральную величину. */
      .обойма--a4 { zoom: 0.52; }
      .обойма--визитка { zoom: 1.1; }
    </style>`;

  const блоки = ДОКУМЕНТЫ.map((док) => {
    const ф = ФОРМАТЫ[док.формат];
    const листы = Object.keys(СЛОВАРЬ)
      .map(
        (локаль) => `
        <div class="обойма обойма--${док.формат}">
${разметкаЛиста(док, локаль)}
          <p class="обойма__подпись">${локаль === 'ru' ? 'русская версия' : 'иврит — черновик до вычитки носителем'}</p>
        </div>`,
      )
      .join('\n');

    return `
      <section class="документ" id="${док.ключ}">
        <div class="документ__шапка">
          <h2 class="документ__имя">${док.имя} <span class="метка метка--факт">${ф.изделие}</span></h2>
          <p class="документ__пояснение">${док.пояснение}</p>
        </div>
        <div class="документ__листы">
${листы}
        </div>
      </section>`;
  }).join('\n');

  return `${шапкаСтраницы('Печать и документы · Fixli', стили)}
  <body>
    <div class="полоса витрина">
      <header class="шапка">
        <p class="шапка__крошки">
          <a href="../../book/index.html">Брендбук Fixli</a> · Кит · Печать и документы
        </p>
        <h1>Печать и документы</h1>
        <p class="шапка__лид">
          Восемь документов на двух языках. Визитку режет типография, остальное печатается в офисе
          на обычном принтере — поэтому под обрез уходит только круг на визитке, а на листах A4 нет
          ни одной заливки, доходящей до кромки: принтер оставляет белое поле и срезал бы её.
        </p>
        <p class="шапка__лид">
          <span class="метка метка--решение">наше решение</span>
          Налогового счёта <span dir="rtl">חשבונית מס</span> здесь нет и не будет: с 2024 года он
          получает номер распределения в <span dir="rtl">רשות המסים</span> и выпускается
          сертифицированным ПО. Мы печатаем счёт к оплате, а налоговый выдаёт бухгалтерский сервис.
        </p>
        <p class="шапка__лид">
          <span class="метка метка--вопрос">ждёт заказчика</span>
          Реквизиты. Пока документа о регистрации нет, номер плательщика печатается заглушкой на
          жёлтом — в двух документах, четырьмя полями.
        </p>
      </header>
${блоки}
      <p class="бланк__подпись-автора">Made by Dmitry Khinkis</p>
    </div>
  </body>
</html>`;
}

/* ═══ 10. Наряд слово в слово с телеграмным ═══════════════════════════════ */

const нарядИсходник = readFileSync(
  join(КОРЕНЬ, 'apps', 'worker', 'src', 'telegram', 'job-message.ts'),
  'utf8',
);

/* Ярлыки блоков телеграмного наряда, в порядке появления. Сверяются не по
 * списку, зашитому здесь, а по самому боту: появится в наряде новый блок —
 * печатный бланк упадёт, пока в нём не заведут строку под него. */
const ярлыкиБота = [
  ...new Set([...нарядИсходник.matchAll(/[`'"]([А-ЯЁ][А-Яа-яЁё ]{2,20}): /g)].map((м) => м[1])),
];

if (ярлыкиБота.length < 5)
  беда('наряд разошёлся', `в job-message.ts разобрано ${ярлыкиБота.length} блоков — сломался разбор`);

for (const состояние of ['время не назначено', 'адрес не записан']) {
  if (!нарядИсходник.includes(состояние))
    беда(
      'наряд разошёлся',
      `в job-message.ts больше нет состояния «${состояние}» — печатный наряд обещает то, чего бот не говорит`,
    );
  if (!Object.values(СЛОВАРЬ.ru).some((з) => typeof з === 'string' && з.includes(состояние)))
    беда('наряд разошёлся', `в печатном наряде нет состояния «${состояние}», а в боте оно есть`);
}

/* ═══ 14. Пример в смете сходится с прайсом проекта ═══════════════════════
 * Числа в образце заполнения — не украшение: по ним читают, как считается
 * заказ. Прайс уже менялся однажды целой фазой (калькулятор по предметам), и
 * правило проекта на такой случай известно — связанные числа трогают одной
 * правкой. Здесь связь между документом и прайсом проверяется, а не
 * держится на памяти. */
const прайс = readFileSync(
  join(КОРЕНЬ, 'packages', 'quote', 'src', 'data', 'pricing.ts'),
  'utf8',
);
const ставкаПрайса = Number(/shekelPerPersonHour:\s*(\d+)/.exec(прайс)?.[1]);
if (!Number.isFinite(ставкаПрайса))
  беда('прайс', 'в pricing.ts не найдена shekelPerPersonHour — сломался разбор');
else {
  const часыПримера = 3 * 6;
  const суммаПримера = Number(СЛОВАРЬ.ru.примерЧасыСумма?.replace(/\D/g, ''));
  if (суммаПримера !== ставкаПрайса * часыПримера)
    беда(
      'смета разошлась с прайсом',
      `в примере ${суммаПримера} ₪ за ${часыПримера} человеко-часов, это ` +
        `${(суммаПримера / часыПримера).toFixed(0)} ₪/час, а в прайсе ${ставкаПрайса} ₪/час`,
    );
}

/* ═══ Соседние файлы направления ══════════════════════════════════════════ */

for (const файл of ['README.md', 'реестр-обещаний.md', 'тз-типография.md', 'печать.css', 'документы.mjs'])
  if (!existsSync(join(ЗДЕСЬ, файл))) беда('файл направления', `${файл} не найден`);

for (const знак of ['fixli-знак.svg', 'fixli-колонна.svg'])
  if (!existsSync(join(ЗДЕСЬ, '..', '..', 'знак', знак)))
    беда('файл знака', `brand/знак/${знак} не найден`);

/* ═══ Проверки по отрисованной странице ═══════════════════════════════════ */

const СТОП_СЛОВА = [
  { что: /страхов/i, почему: 'страховки у компании нет — Игорь, 2026-08-10' },
  { что: /ביטוח/, почему: 'страховки у компании нет' },
  { что: /гаранти/i, почему: 'гарантия не подтверждена заказчиком' },
  { что: /24\s*\/\s*7/, почему: 'компания работает не круглосуточно' },
  { что: /скидк/i, почему: 'скидок в прайсе нет' },
  { что: /хранени[ея]\s+вещ/i, почему: 'услуги не существует — Дима, 2026-08-10' },
  { что: /\bFIXLI\b/, почему: 'капс отменён 2026-08-10, в тексте пишется Fixli' },
  /*
   * Запрещён служебный адрес и второй домен, а не адрес сайта вообще.
   *
   * До 2026-08-19 здесь стояло `fixli(home|group)\.co\.il` — «домены не
   * куплены». Условие изменилось: `fixlihome.co.il` внесён в реестр `.co.il`
   * 18 августа и отвечает по HTTPS, то есть печатать его теперь можно и нужно.
   * Запрет остаётся на `fixligroup.co.il` (его решено не покупать вовсе) и на
   * служебный хост Pages: он закрыт от индексации нашим же заголовком, и лист,
   * ведущий человека на страницу, которую мы сами спрятали, обещает то, чего
   * не выполнит. На бумаге это дороже, чем на экране: лист живёт до тиража.
   */
  { что: /fixligroup\.co\.il/i, почему: 'второй домен решено не покупать' },
  { что: /pages\.dev/i, почему: 'служебный адрес закрыт от индексации — печатается только fixlihome.co.il' },
  { что: /[\w.]+@[\w.]+\.\w+/, почему: 'почтового ящика у компании нет' },
];

const браузер = await chromium.launch();
const страница = await браузер.newPage({ deviceScaleFactor: 2 });

/* Два прохода, а не один. Сначала проверяются ВСЕ листы, и только потом
 * пишутся PDF и PNG: иначе первый десяток файлов успевал обновиться до того,
 * как падал одиннадцатый, и в папке лежала смесь нового со старым — ровно то
 * состояние, из-за которого потом невозможно понять, что ушло в типографию. */
const листы = [];
for (const док of ДОКУМЕНТЫ)
  for (const локаль of Object.keys(СЛОВАРЬ)) листы.push({ док, локаль });

for (const { док, локаль } of листы) {
  const ф = ФОРМАТЫ[док.формат];
  {
    const временный = join(ЗДЕСЬ, `.лист-${док.ключ}-${локаль}.html`);
    writeFileSync(временный, страницаЛиста(док, локаль), 'utf8');
    await страница.goto(pathToFileURL(временный).href, { waitUntil: 'networkidle' });
    await страница.evaluate(() => document.fonts.ready);

    const где = `${док.ключ}·${локаль}`;

    /* 5. Формат листа. */
    const размер = await страница.locator('.лист').boundingBox();
    const шир = размер.width / ПИКСЕЛЕЙ_В_ММ;
    const выс = размер.height / ПИКСЕЛЕЙ_В_ММ;
    if (Math.abs(шир - ф.ширина) > ДОПУСК_ММ || Math.abs(выс - ф.высота) > ДОПУСК_ММ)
      беда(
        'формат листа',
        `${где} — отрисован ${шир.toFixed(1)} × ${выс.toFixed(1)} мм, объявлен ${ф.ширина} × ${ф.высота}`,
      );

    /* 6–8. Знак: пропорция, объявленная ширина, печатный минимум. */
    const знаки = await страница.evaluate(() =>
      [...document.querySelectorAll('img[data-знак]')].map((img) => ({
        объявлено: Number(img.dataset['знак']),
        ширина: img.getBoundingClientRect().width,
        высота: img.getBoundingClientRect().height,
        своя: img.naturalWidth,
        своявысота: img.naturalHeight,
      })),
    );
    for (const з of знаки) {
      const рамкаММ = з.ширина / ПИКСЕЛЕЙ_В_ММ;
      const знакММ = рамкаММ * ДОЛЯ_ЗНАКА;
      const пропорцияФайла = з.своя / з.своявысота;
      const пропорцияРамки = з.ширина / з.высота;

      if (Math.abs(пропорцияФайла - пропорцияРамки) > 0.02)
        беда('знак растянут', `${где} — рамка ${пропорцияРамки.toFixed(3)}, файл ${пропорцияФайла.toFixed(3)}`);

      if (Math.abs(знакММ - з.объявлено) > 0.4)
        беда(
          'знак не того размера',
          `${где} — сам знак ${знакММ.toFixed(1)} мм, объявлено ${з.объявлено}. Внутри файла есть поля, рамка шире знака на 5 %`,
        );

      if (знакММ < ЗНАК_МИНИМУМ_ММ)
        беда(
          'знак мельче минимума',
          `${где} — ${знакММ.toFixed(1)} мм при печатном минимуме ${ЗНАК_МИНИМУМ_ММ} мм`,
        );
    }

    /* 9. Безопасное поле от линии реза. */
    const край = ф.вылет + БЕЗОПАСНОЕ_ПОЛЕ_ММ;
    /* Меряются ТЕКСТОВЫЕ УЗЛЫ, а не элементы. Первая версия правила пропускала
     * любой элемент, у которого есть дети, — и триада визитки «Качество ·
     * Ответственность · Результат» не проверялась вовсе: внутри неё лежат
     * span-точки, значит элемент «с детьми». Слово «Результат» могло уехать
     * под нож, а сторож молчал бы. Range меряет ровно то, что видит глаз. */
    const нарушители = await страница.evaluate(
      ({ край, пвм }) => {
        const лист = document.querySelector('.лист').getBoundingClientRect();
        const обход = document.createTreeWalker(document.querySelector('.лист'), NodeFilter.SHOW_TEXT);
        const плохие = [];
        for (let узел = обход.nextNode(); узел; узел = обход.nextNode()) {
          const текст = узел.textContent.trim();
          if (!текст) continue;
          const диапазон = document.createRange();
          диапазон.selectNodeContents(узел);
          for (const r of диапазон.getClientRects()) {
            if (r.width === 0 || r.height === 0) continue;
            const отступы = [
              r.left - лист.left,
              лист.right - r.right,
              r.top - лист.top,
              лист.bottom - r.bottom,
            ].map((v) => v / пвм);
            if (Math.min(...отступы) < край - 0.3)
              плохие.push(`«${текст.slice(0, 28)}» — ${Math.min(...отступы).toFixed(1)} мм`);
          }
        }
        return плохие;
      },
      { край, пвм: ПИКСЕЛЕЙ_В_ММ },
    );
    for (const н of нарушители)
      беда('безопасное поле', `${где} — ${н}, нужно не меньше ${край} мм от кромки листа`);

    /* 10. Состав и порядок блоков печатного наряда равны телеграмным. */
    if (док.ключ === 'наряд' && локаль === 'ru') {
      const ярлыкиЛиста = await страница.evaluate(() =>
        [...document.querySelectorAll('.наряд__ярлык')].map((у) => у.textContent.trim()),
      );
      if (ярлыкиЛиста.join(' → ') !== ярлыкиБота.join(' → '))
        беда(
          'наряд разошёлся',
          `бот говорит «${ярлыкиБота.join(' → ')}», бумага — «${ярлыкиЛиста.join(' → ')}». ` +
            'Два разных наряда на одну смену — это работник, приехавший не туда',
        );
    }

    /* 15. Лист набран Rubik, а не подстановкой. Шрифт лежит рядом файлом и
     * подключается относительным путём: стоит переехать папке — и PDF молча
     * выйдет системной гарнитурой. На экране это заметно не сразу, в тираже —
     * поздно.
     *
     * Правило проверяется ЗАМЕРОМ, а не `document.fonts.check`, и это вывод из
     * двух ложных срабатываний подряд. Первая версия спрашивала про латиницу,
     * кириллицу и иврит сразу — одиннадцать нарушений на ровном месте:
     * подмножества Rubik лежат четырьмя файлами и грузятся лениво, поэтому на
     * русской визитке ивритского фейса нет и быть не должно. Вторая версия
     * спрашивала посимвольно и обвинила символ шекеля: `check` вернул false,
     * хотя замер ширины показал 88,2 против 77,6 у подстановки — то есть ₪
     * рисуется именно Rubik. Причина в том, что U+20AA объявлен сразу в двух
     * подмножествах, и одно из них не загружено.
     *
     * Замер отвечает на тот вопрос, ради которого правило и заводилось:
     * применилась гарнитура или лист набран системной. Ложное правило хуже
     * отсутствующего — оно приучает не читать вывод сторожа. */
    const гарнитура = await страница.evaluate(() => {
      const текст = document.querySelector('.лист').innerText.replace(/\s+/g, ' ').slice(0, 300);
      const мера = (семейство) => {
        const холст = document.createElement('canvas').getContext('2d');
        холст.font = `100px ${семейство}`;
        return холст.measureText(текст).width;
      };
      return {
        своя: мера('Rubik'),
        подстановка: мера('ЗаведомоНесуществующаяГарнитура'),
        фейсов: [...document.fonts].filter((ф) => ф.status === 'loaded').length,
      };
    });
    if (гарнитура.фейсов === 0)
      беда('шрифт не загружен', `${где} — ни один @font-face Rubik не в состоянии loaded`);
    else if (Math.abs(гарнитура.своя - гарнитура.подстановка) < 0.5)
      беда(
        'шрифт не применился',
        `${где} — текст в Rubik и в системной гарнитуре одной ширины (${гарнитура.своя.toFixed(0)}), ` +
          'значит лист набран подстановкой и уйдёт в PDF не тем шрифтом',
      );

    /* 12. Локаль не протекла. Найдено глазами уже после того, как одиннадцать
     * правил дали зелёный: в ивритской смете количество стояло по-русски —
     * «3 чел. × 6 ч». Захардкоженная строка, одна на обе локали, и ни один
     * ассерт её не видел. Кириллицы в ивритском листе не должно быть вовсе;
     * иврит в русском допустим только как термин из белого списка — названия
     * израильских документов и реквизитов переводить нельзя, клиент ищет
     * глазами именно их. */
    const ТЕРМИНЫ_НА_ИВРИТЕ = ['חשבונית מס', 'רשות המסים', 'ע.מ.', 'ח.פ.', 'דרישת תשלום', 'הצעת מחיר'];
    const текстЛиста = await страница.locator('.лист').innerText();
    if (локаль === 'he') {
      const кириллица = текстЛиста.match(/[А-Яа-яЁё]{2,}/);
      if (кириллица)
        беда('локаль протекла', `${где} — в ивритском листе русский текст «${кириллица[0]}»`);
    } else {
      let без = текстЛиста;
      for (const т of ТЕРМИНЫ_НА_ИВРИТЕ) без = без.split(т).join('');
      const иврит = без.match(/[֐-׿]{2,}/);
      if (иврит)
        беда(
          'локаль протекла',
          `${где} — в русском листе иврит «${иврит[0]}», и это не термин из белого списка`,
        );
    }

    /* 3–4. Обещания и стоп-слова — по отрисованному тексту. */
    const ключи = await страница.evaluate(() =>
      [...document.querySelectorAll('[data-обещание]')].map((у) => у.dataset['обещание']),
    );
    for (const ключ of ключи) {
      const статус = статусПоКлючу.get(ключ);
      if (!статус) беда('обещание без источника', `${где} — ключа «${ключ}» нет в реестре`);
      else if (статус === '🔴') беда('запрещённое обещание', `${где} — ключ «${ключ}» помечен 🔴`);
    }

    for (const стоп of СТОП_СЛОВА) {
      const найдено = текстЛиста.match(стоп.что);
      /* Сноска про налоговый счёт обязана называть חשבונית מס — это её смысл. */
      if (найдено) беда('стоп-слово', `${где} — «${найдено[0]}»: ${стоп.почему}`);
    }

    /* 11. Иврит: телефон и суммы идут слева направо. */
    if (локаль === 'he') {
      const беглецы = await страница.evaluate(() => {
        const плохие = [];
        for (const узел of document.querySelectorAll('.лист *')) {
          const текст = (узел.textContent ?? '').trim();
          if (узел.children.length > 0) continue;
          const числовой = /^[\d\s .,–-]*(₪|)$/.test(текст) && /\d/.test(текст);
          if (!числовой) continue;
          const dir = узел.closest('[dir]')?.getAttribute('dir');
          if (dir !== 'ltr') плохие.push(текст.slice(0, 24));
        }
        return плохие;
      });
      for (const б of беглецы)
        беда('число без dir=ltr', `${где} — «${б}» развернётся в RTL-контексте`);

      /*
       * И обратное правило, к тому же атрибуту: `dir="ltr"` ставится на
       * строчный элемент, а не на блочный. Он задаёт не только порядок
       * символов, но и базовое направление абзаца, а от него зависит
       * выравнивание. Строка адреса сайта на ивритской визитке приехала
       * абзацем с `dir="ltr"` и прижалась к левому краю, пока номер над ней
       * стоял у правого: порядок символов верный, все пятнадцать правил
       * зелёные, нашли глаза. Лечится оборачиванием в `<span dir="ltr">` —
       * тем же приёмом, каким набран телефон.
       */
      const блочные = await страница.evaluate(() => {
        const плохие = [];
        for (const узел of document.querySelectorAll('.лист [dir="ltr"]')) {
          if (getComputedStyle(узел).display.startsWith('inline')) continue;
          /* Внутри flex и grid положение задаёт не `text-align`, а раскладка,
             и там `dir` ничего не переворачивает. Заодно это снимает ложное
             срабатывание на строчных элементах: дети flex-контейнера
             приводятся к блочным, и телефон на визитке попадал под правило. */
          const родитель = узел.parentElement;
          const раскладка = родитель ? getComputedStyle(родитель).display : '';
          if (раскладка.includes('flex') || раскладка.includes('grid')) continue;
          плохие.push(узел.className || узел.tagName);
        }
        return плохие;
      });
      for (const б of блочные)
        беда('dir=ltr на блоке', `${где} — «${б}» переключает выравнивание строки; оберни текст в <span dir="ltr">`);
    }
  }
}

const { unlinkSync } = await import('node:fs');
