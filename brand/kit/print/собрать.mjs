mkdirSync(join(выход, 'pdf'), { recursive: true });
mkdirSync(join(выход, 'png'), { recursive: true });

const снято = [];
for (const { док, локаль } of листы) {
  const ф = ФОРМАТЫ[док.формат];
  const временный = join(ЗДЕСЬ, `.лист-${док.ключ}-${локаль}.html`);
  writeFileSync(временный, страницаЛиста(док, локаль), 'utf8');
  await страница.goto(pathToFileURL(временный).href, { waitUntil: 'networkidle' });
  await страница.evaluate(() => document.fonts.ready);

  const имя = `${док.ключ}-${локаль}`;
  await страница.pdf({
    path: join(выход, 'pdf', `${имя}.pdf`),
    width: `${ф.ширина}mm`,
    height: `${ф.высота}mm`,
    printBackground: true,
    margin: { top: '0', right: '0', bottom: '0', left: '0' },
  });
  /* PNG показывает ИЗДЕЛИЕ, PDF содержит вылет. Разница не косметическая:
   * картинку отправляют заказчику со словами «вот как будет выглядеть», и
   * показывать ему три лишних миллиметра по кромке, которые уйдут под нож, —
   * значит показывать не то, что он получит. Кадр обрезается по линии реза. */
  const рамка = await страница.locator('.лист').boundingBox();
  if (!рамка) {
    беда('лист не отрисован', `${имя} — на странице нет элемента .лист`);
  } else if (ф.вылет > 0) {
    /* Обрезка делается `страница.screenshot`, а не `locator.screenshot`:
     * у локатора опции `clip` нет вовсе, и переданная ему она молча
     * игнорируется — первая версия так и выдавала кадр с вылетом, ничем не
     * отличавшийся от прежнего. */
    const вылетPX = ф.вылет * ПИКСЕЛЕЙ_В_ММ;
    await страница.screenshot({
      path: join(выход, 'png', `${имя}.png`),
      clip: {
        x: рамка.x + вылетPX,
        y: рамка.y + вылетPX,
        width: рамка.width - вылетPX * 2,
        height: рамка.height - вылетPX * 2,
      },
    });
  } else {
    await страница.locator('.лист').screenshot({ path: join(выход, 'png', `${имя}.png`) });
  }

  /* 13. Формат ГОТОВОГО PDF, а не отрисованного листа. Между ними стоит
   * конвертер Chromium, и проверять надо то, что уедет в типографию: он
   * округляет размер страницы до целых точек, и знать, насколько именно,
   * важнее, чем верить, что вылет 3 мм остался ровно тремя. */
  const пдф = readFileSync(join(выход, 'pdf', `${имя}.pdf`));
  const бокс = /\/MediaBox\s*\[([^\]]+)\]/.exec(пдф.toString('latin1'));
  if (!бокс) беда('PDF без формата', `${имя} — в файле нет MediaBox`);
  else {
    const [x0, y0, x1, y1] = бокс[1].trim().split(/\s+/).map(Number);
    const ш = ((x1 - x0) / 72) * 25.4;
    const в = ((y1 - y0) / 72) * 25.4;
    if (Math.abs(ш - ф.ширина) > 0.5 || Math.abs(в - ф.высота) > 0.5)
      беда(
        'формат PDF',
        `${имя} — страница ${ш.toFixed(1)} × ${в.toFixed(1)} мм, объявлено ${ф.ширина} × ${ф.высота}`,
      );
  }

  снято.push(имя);
}

