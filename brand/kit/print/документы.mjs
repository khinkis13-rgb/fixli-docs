/**
 * Печать и документы Fixli — тексты и разметка листов. ЭТО ТОТ ФАЙЛ, КОТОРЫЙ ПРАВЯТ.
 *
 * ── Почему здесь данные, а не готовый HTML, как в двух прошлых направлениях кита
 * В `kit/ads` и `kit/transport` правится сам HTML: там макет — картинка, и её
 * правят глазами. Здесь другая природа: документ — это шаблон с полями, и
 * каждый существует в двух локалях сразу. Восемь документов на двух языках —
 * шестнадцать листов, а расхождение между русской и ивритской версией счёта
 * заметит не тест, а клиент. Поэтому текст лежит в одном словаре, разметка
 * пишется один раз, а локаль подставляется. Витрину и PDF собирает
 * `собрать.mjs`; руками витрину не правят — она пересобирается целиком.
 *
 * ── Что здесь нельзя делать
 * 1. Ставить знак набранным текстом. Буквы знака нарисованы, а не набраны, и
 *    подстановкой шрифта он не воспроизводится — только файлом из `brand/знак/`;
 * 2. Печатать служебный адрес сайта (`fixli-site.pages.dev`) или второй домен
 *    `fixligroup.co.il`: первый закрыт от индексации нашим же заголовком, второй
 *    решено не покупать. Боевой `fixlihome.co.il` печатать **можно и нужно** —
 *    запрет снят 2026-08-19, когда домен начал отвечать (правило общее с
 *    рекламой и транспортом);
 * 3. Писать строку, у которой нет ключа `data-обещание` в `реестр-обещаний.md`.
 *    Сборка не начнётся;
 * 4. Выдавать `דרישת תשלום` за `חשבונית מס`. Налоговый счёт с 2024 года
 *    получает номер распределения в `רשות המסים` и выпускается сертифицированным
 *    ПО — наш бланк им не станет ни при каких реквизитах.
 *
 * ── Иврит здесь черновой
 * Написан нами, носителем не вычитан — то же состояние, что у ивритских
 * креативов и страницы знакомства. До вычитки ивритские PDF не отдаются в
 * типографию и не уходят клиенту.
 */

