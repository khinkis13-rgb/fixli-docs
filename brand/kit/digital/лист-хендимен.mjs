/**
 * Лист сравнения для знака «хендимен».
 *
 * ЗАЧЕМ
 * -----
 * Знак `handyman` из набора услуг сайта в натуральную величину читается холмом
 * с капюшоном, а не инструментом. Нашли глаза на печатном макете наклеек
 * 18.09.2026, подтвердил Дмитрий кропом.
 *
 * Разбор существующего пути показывает, что задумывался рожковый ключ, но:
 *  · ручка нарисована как треугольник до угла (3,21), а не как узкая рукоять —
 *    отсюда «холм», занимающий половину сетки;
 *  · головка ключа лежит отдельной незамкнутой дугой поверх треугольника —
 *    отсюда «капюшон».
 *
 * ПОЧЕМУ ЛИСТ, А НЕ ОПИСАНИЕ СЛОВАМИ
 * ----------------------------------
 * В этом проекте знаки уже дважды выбирались листом сравнения, и оба раза он
 * отменял выбор, сделанный на словах: торшер читался зонтом, кровать чемоданом.
 * Знак живёт на четырёх размерах сразу — 16 px в витрине, 34 px на карточке
 * услуги, ~105 мм на борту фургона, — и решает самый мелкий.
 *
 * Здесь же рядом стоят соседи по набору: знак обязан отличаться не только от
 * «холма», но и от грузовика, коробки и дивана.
 *
 * Запуск: node brand/kit/digital/лист-хендимен.mjs
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from '@playwright/test';

const ЗДЕСЬ = dirname(fileURLToPath(import.meta.url));
const КОРЕНЬ = join(ЗДЕСЬ, '..', '..', '..');
const ОРАНЖЕВЫЙ = '#F38025';

/* Соседи по набору читаются из живого исходника: копия пути здесь разошлась бы
 * молча, а лист ровно затем и нужен, чтобы сравнивать с тем, что есть. */
const исходник = readFileSync(join(КОРЕНЬ, 'apps/site/src/components/brand/ServiceIcon.astro'), 'utf8');
const путьИз = (вид) => исходник.match(new RegExp(`\\n\\s*${вид}: '([^']+)'`))[1];

const СОСЕДИ = ['moving', 'packing', 'furniture'].map((вид) => ({ имя: вид, d: путьИз(вид) }));

/* ─── Кандидаты ───────────────────────────────────────────────────────────
 *
 * Стиль набора: сетка 24, контур 1,6, скруглённые концы, без заливки. Силуэт
 * предмета замкнутым контуром — так нарисованы и грузовик, и коробка, и диван.
 */
const КАНДИДАТЫ = [
  {
    ключ: 'было',
    имя: 'Было до 18.09.2026',
    отсеян: 'читается холмом с капюшоном: рукоять треугольником, головка отдельной дугой поверх',
    /* Литерал, и это осознанное исключение из правила «пути читаются из
     * исходника»: отменённой редакции больше нигде нет, а лист обязан
     * показывать, от чего ушли. Читать её из `ServiceIcon.astro` нельзя —
     * там теперь молоток, и строка «было» показывала бы «стало». */
    d: 'M14.7 6.3a4 4 0 0 0 5 5L21 21H3l7.5-7.5a4 4 0 0 1 5-5z M14.5 3.5a4 4 0 0 1 5.5 5.5',
  },
  {
    ключ: 'ключ',
    имя: 'A · рожковый ключ',
    /* Вторая редакция. Первая была тоньше (полуширина рукояти 1,6, головка 3,0)
     * и на 24 px читалась ножом: зев пропадал раньше, чем становился виден.
     * Утолщена рукоять до 2,0, головка до 3,6, зев сделан уже и глубже —
     * прорезь должна оставаться прорезью, когда всё остальное слипается. */
    d: 'M8.2 18.6 L13.9 12.9 L15.6 13.5 L19.4 9.8 L17.5 7.9 L15.4 10 L14 8.6 '
      + 'L16.1 6.5 L14.3 4.7 L10.5 8.4 L11.1 10.1 L5.4 15.8 A2 2 0 0 0 8.2 18.6 Z',
  },
  {
    ключ: 'молоток',
    имя: 'B · молоток — ПРИНЯТ 18.09.2026',
    d: 'M9.5 4.5 L19 4.5 A1 1 0 0 1 20 5.5 L20 8.5 A1 1 0 0 1 19 9.5 L9.5 9.5 '
      + 'L7 7 Z M12.5 9.5 L12.5 19.5 A1.4 1.4 0 0 1 9.7 19.5 L9.7 9.5',
  },
  {
    ключ: 'отвёртка',
    имя: 'отсеяно · отвёртка',
    отсеян: 'на 160 px читается ножом: у контура нет ни буртика, ни граней',
    d: 'M6.1 21.1 L11.6 15.6 L10.6 14.6 L18.1 7.1 L16.9 5.9 L9.4 13.4 L8.4 12.4 '
      + 'L2.9 17.9 A2.2 2.2 0 0 0 6.1 21.1 Z M8.4 12.4 L11.6 15.6',
  },
  {
    ключ: 'крест',
    имя: 'отсеяно · ключ и отвёртка крестом',
    отсеян: 'каша на всех размерах, на 16 px — пятно',
    группа: true,
  },
];

const иконка = (d, размер, толщина = 1.6) =>
  `<svg width="${размер}" height="${размер}" viewBox="0 0 24 24" fill="none"
     stroke="${ОРАНЖЕВЫЙ}" stroke-width="${толщина}" stroke-linecap="round" stroke-linejoin="round"
     style="display:block"><path d="${d}"/></svg>`;

const крест = (размер) => {
  const ключ = КАНДИДАТЫ.find((к) => к.ключ === 'ключ').d;
  const отв = КАНДИДАТЫ.find((к) => к.ключ === 'отвёртка').d;
  return `<svg width="${размер}" height="${размер}" viewBox="0 0 24 24" fill="none"
     stroke="${ОРАНЖЕВЫЙ}" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"
     style="display:block">
     <g transform="translate(12 12) rotate(-18) scale(0.72) translate(-12 -12) translate(0 -1)"><path d="${ключ}"/></g>
     <g transform="translate(12 12) rotate(36) scale(0.72) translate(-12 -12) translate(0 2)"><path d="${отв}"/></g>
   </svg>`;
};

const РАЗМЕРЫ = [16, 24, 34, 64, 160];

const строка = (к) => `
  <tr class="${к.отсеян ? 'отсеян' : ''}">
    <th>${к.имя}${к.отсеян ? `<br><span class="почему">${к.отсеян}</span>` : ''}</th>
    ${РАЗМЕРЫ.map((р) => `<td>${к.группа ? крест(р) : иконка(к.d, р)}</td>`).join('')}
  </tr>`;

const соседи = `
  <tr class="разрыв"><th colspan="6">Соседи по набору — знак обязан отличаться и от них</th></tr>
  ${СОСЕДИ.map((с) => `<tr class="сосед"><th>${с.имя}</th>${РАЗМЕРЫ.map((р) => `<td>${иконка(с.d, р)}</td>`).join('')}</tr>`).join('')}`;

const страница = `<!doctype html><meta charset="utf-8">
<style>
  body{background:#fff;font:14px/1.4 system-ui;margin:0;padding:28px;color:#22303f}
  h1{font-size:19px;margin:0 0 6px;color:#12438F}
  p{margin:0 0 20px;color:#5b6672;max-width:900px}
  table{border-collapse:collapse}
  th{text-align:left;font-weight:600;padding:14px 18px 14px 0;white-space:nowrap;vertical-align:middle}
  td{padding:14px 26px;vertical-align:middle}
  thead th{color:#8a95a3;font-weight:500;font-size:12px}
  tr.разрыв th{padding-top:30px;color:#8a95a3;font-weight:500;font-size:12px}
  tr.сосед{opacity:.75}
  tr.отсеян{opacity:.45}
  .почему{font-weight:400;font-size:12px;color:#8a95a3;white-space:normal;display:block;max-width:220px;margin-top:4px}
  tr+tr th{border-top:1px solid #eef1f5}
</style>
<h1>Знак «хендимен»: лист сравнения</h1>
<p>Решает самый мелкий размер: 16&nbsp;px — витрина кита цифры, 34&nbsp;px — карточка услуги
на сайте, 160&nbsp;px здесь соответствует ~105&nbsp;мм на борту фургона. Знак должен читаться
инструментом на всех четырёх и не совпадать с соседями по набору.</p>
<table>
  <thead><tr><th></th>${РАЗМЕРЫ.map((р) => `<th>${р} px</th>`).join('')}</tr></thead>
  <tbody>${КАНДИДАТЫ.map(строка).join('')}${соседи}</tbody>
</table>`;

const браузер = await chromium.launch();
const стр = await браузер.newPage({ viewport: { width: 1160, height: 900 }, deviceScaleFactor: 2 });
await стр.setContent(страница);
const путь = join(ЗДЕСЬ, 'лист-хендимен.png');
await стр.screenshot({ path: путь, fullPage: true });
await стр.screenshot({ path: join(homedir(), 'Downloads', 'Fixli-знак-хендимен.png'), fullPage: true });
await браузер.close();

console.log(`Лист сравнения: ${путь.replace(КОРЕНЬ + '/', '')}`);
console.log('Копия для просмотра: ~/Downloads/Fixli-знак-хендимен.png');
