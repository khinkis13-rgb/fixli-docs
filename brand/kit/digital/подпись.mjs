/**
 * Подпись в почте — данные и разметка.
 *
 * **Правится здесь, а не в готовых файлах.** `подпись/*.html` и `подпись/*.txt`
 * собираются из этого модуля и перезаписываются целиком: правка в готовом
 * файле проживёт до следующей сборки.
 *
 * ── Три ограничения, из которых выросла вся разметка ──────────────────────
 *
 * **1. Почтовый клиент — не браузер.** Gmail вырезает `<style>` целиком,
 * Outlook рисует движком Word: `flex`, `grid`, внешние классы и половина
 * свойств не работают. Поэтому здесь таблица и только инлайн-стили — способ,
 * который в почте держится двадцать лет. Это не архаика ради архаики: подпись
 * уезжает в чужой клиент, где ни один наш файл не подключён.
 *
 * **2. Шрифта бренда в почте нет.** Rubik лежит у нас в репозитории и не
 * доедет до получателя: `@font-face` в подписи не работает, а внешний шрифт
 * почтовые клиенты не грузят. Поэтому подпись набирается системным стеком с
 * теми же метриками, что у Rubik по духу, и это записано как честная граница,
 * а не как ошибка. Фирменное в подписи держат знак и цвет, а не гарнитура.
 *
 * **3. Знак — картинка по абсолютному адресу.** Файлом из репозитория его не
 * поставить: письмо уходит с чужой машины. Вложением — тоже нельзя, иначе у
 * каждого письма появляется «скрепка», за которой картинка подписи, и
 * настоящее вложение в списке теряется. Остаётся `https://`, и адрес взят
 * боевой: `fixlihome.co.il`, куда сайт выкатывается из `main`. До 2026-08-19
 * здесь стоял служебный `fixli-site.pages.dev` — домен был куплен, но не
 * внесён в реестр `.co.il`.
 *
 * **Адрес сайта в подписи есть с 2026-08-19.** Пока домен не отвечал, строки
 * не было по тому же правилу, что в рекламе и на бортах: печатать адрес,
 * который не открывается, нельзя. Теперь он открывается — и стоит последней
 * строкой, ссылкой, вместе с картинкой знака на том же хосте.
 *
 * **Email-адреса в подписи тоже нет, и это не пропуск.** Корпоративной почты
 * у компании нет; адрес, с которого письмо пришло, читатель и так видит в
 * шапке письма. Дублировать его в подписи — строка, которая ничего не
 * добавляет и устаревает первой.
 */

import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

import { СЛОВАРЬ } from '../print/документы.mjs';

/**
 * Значения красок читаются из `brand/tokens.css`, а не пишутся здесь.
 *
 * В готовой подписи они всё равно окажутся литералами — CSS-переменных в почте
 * не существует, — но литерал, набранный руками, разъезжается с системой молча.
 * Так уже было: перетрассированный знак нёс `#F28123` вместо `#F38025`, и
 * первый экран сайта полдня показывал не фирменный оранжевый рядом с фирменным
 * в шапке.
 */
function токен(имя) {
  const путь = fileURLToPath(new URL('../../tokens.css', import.meta.url));
  const css = readFileSync(путь, 'utf8');
  const найдено = new RegExp(`--${имя}:\\s*(#[0-9a-fA-F]{3,8})`).exec(css);
  if (!найдено) throw new Error(`В brand/tokens.css нет токена --${имя}`);
  return найдено[1];
}

/** Боевой адрес сайта. Один на картинку знака и на строку контактов. */
export const САЙТ = 'fixlihome.co.il';

/**
 * Знак по живому адресу. Ширина в атрибуте обязательна: Outlook игнорирует
 * `max-width` в стиле и рисует картинку в натуральную величину — 436 px,
 * то есть подпись шире письма.
 */
export const ЗНАК_URL = `https://${САЙТ}/brand/fixli-logo.png`;
export const ЗНАК_ШИРИНА = 104;
/** Пропорция файла 436 × 198. Высота считается, а не выдумывается. */
export const ЗНАК_ВЫСОТА = Math.round((ЗНАК_ШИРИНА * 198) / 436);

export const ЦВЕТА = {
  navy: токен('fx-navy'),
  navyDeep: токен('fx-navy-deep'),
  text: токен('fx-ink-soft'),
  line: токен('fx-line'),
};

/**
 * Стек системных шрифтов. Rubik первым — если он у получателя стоит
 * (у нас в команде стоит), подпись наберётся фирменной гарнитурой; у всех
 * остальных подставится системная без скачка метрик.
 */
const ШРИФТ =
  "Rubik, -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, Arial, sans-serif";

/**
 * Люди, у которых есть подпись.
 *
 * Пока один — Игорь, ровно как с визиткой: тираж и подпись считаются на
 * человека, а не на компанию. Имя и роль берутся из словаря печати, чтобы
 * визитка и подпись не разошлись; всё остальное — общее для компании.
 */
export const ПЕРСОНЫ = [
  {
    ключ: 'igor',
    имя: (л) => СЛОВАРЬ[л].имя,
    роль: (л) => СЛОВАРЬ[л].роль,
  },
];

const ТЕЛЕФОН = '055-294-7783';
/** Международная запись — только в ссылке, не в тексте. */
const ТЕЛЕФОН_URL = '+972552947783';

/**
 * Своих формулировок у подписи ровно две на локаль — название компании и слово
 * «телефон». Всё остальное (роль, услуги, гео, «WhatsApp») приходит из словаря
 * печати: подпись и визитка представляют одного человека, и разойтись в том,
 * чем занимается компания, они права не имеют.
 */
const ТЕКСТЫ = {
  ru: { компания: 'Fixli', телефонПодпись: 'Телефон' },
  he: { компания: 'פיקסלי', телефонПодпись: 'טלפון' },
};

const из = (локаль) => ({ ...ТЕКСТЫ[локаль], ...СЛОВАРЬ[локаль] });

/**
 * Разметка подписи.
 *
 * Числа отступов повторяют шкалу бренда (4 / 8 / 12 / 16), но записаны прямо:
 * подставить сюда `var(--fx-space-3)` нельзя — переменная не доедет.
 */
export function подписьHTML(персона, локаль) {
  const т = из(локаль);
  const rtl = локаль === 'he';
  const сторона = rtl ? 'right' : 'left';
  const dir = rtl ? 'rtl' : 'ltr';

  // Телефон всегда `dir="ltr"`: в ивритской строке номер иначе разворачивается
  // и «055-294-7783» читается как «7783-294-055». Та же правка, что в ките
  // печати и в креативах.
  const телефон = `<a href="tel:${ТЕЛЕФОН_URL}" style="color:${ЦВЕТА.navy};text-decoration:none" dir="ltr">${ТЕЛЕФОН}</a>`;

  // Адрес — тоже `dir="ltr"`: латиница в ивритской строке иначе цепляет к себе
  // соседние знаки препинания и переезжает не туда, где её ждёт глаз.
  const сайт = `<a href="https://${САЙТ}/${локаль}/" style="color:${ЦВЕТА.navy};text-decoration:none" dir="ltr">${САЙТ}</a>`;

  return `<table dir="${dir}" cellpadding="0" cellspacing="0" border="0" style="border-collapse:collapse;font-family:${ШРИФТ};font-size:14px;line-height:1.45;color:${ЦВЕТА.text}">
  <tr>
    <td style="padding:0 0 12px 0;text-align:${сторона}">
      <img src="${ЗНАК_URL}" width="${ЗНАК_ШИРИНА}" height="${ЗНАК_ВЫСОТА}" alt="Fixli" style="display:block;border:0;outline:none;text-decoration:none" />
    </td>
  </tr>
  <tr>
    <td style="padding:0;text-align:${сторона}">
      <div style="font-size:15px;font-weight:600;color:${ЦВЕТА.navyDeep}">${персона.имя(локаль)}</div>
      <div style="padding-top:2px">${персона.роль(локаль)}</div>
    </td>
  </tr>
  <tr>
    <td style="padding:10px 0 0 0;border-top:1px solid ${ЦВЕТА.line};text-align:${сторона}">
      <div style="padding-top:8px">${т.whatsapp} · ${т.телефонПодпись}: ${телефон}</div>
      <div style="padding-top:2px">${т.гео}</div>
      <div style="padding-top:2px;color:${ЦВЕТА.navy}">${т.услуги}</div>
      <div style="padding-top:2px">${сайт}</div>
    </td>
  </tr>
</table>`;
}

/**
 * Текстовая версия — не «запасная», а рабочая.
 *
 * Часть переписки идёт простым текстом (ответ с телефона, письмо в поддержку
 * сервиса, форма обратной связи). HTML-подпись там приезжает набором тегов,
 * и человек видит `<table cellpadding=` вместо контактов.
 */
export function подписьТекст(персона, локаль) {
  const т = из(локаль);
  return [
    `${персона.имя(локаль)} — ${персона.роль(локаль)}`,
    т.компания,
    `${т.whatsapp} · ${ТЕЛЕФОН}`,
    т.гео,
    т.услуги,
    САЙТ,
  ].join('\n');
}
