/* Замер центра массы марки. Один раз, на прозрачном холсте и без фона: нужен
   средневзвешенный x непрозрачных пикселей, а не середина рамки. */
const ЦЕНТР_МАССЫ = await (async () => {
  if (!МАРКА) return null;
  const фигура = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${МАРКА.ширина} ${МАРКА.высота}" width="400">
    <circle cx="${МАРКА.cx}" cy="${МАРКА.cy}" r="${МАРКА.r}" fill="#000" />
    <path fill="#000" d="${МАРКА.d}" /></svg>`;
  await страница.setContent('<body style="margin:0"></body>');
  const доля = await страница.evaluate(async (исходник) => {
    const картинка = new Image();
    картинка.src = 'data:image/svg+xml;base64,' + btoa(unescape(encodeURIComponent(исходник)));
    await картинка.decode();
    const холст = document.createElement('canvas');
    холст.width = картинка.width;
    холст.height = картинка.height;
    const ctx = холст.getContext('2d');
    ctx.drawImage(картинка, 0, 0);
    const { data } = ctx.getImageData(0, 0, холст.width, холст.height);
    let сумма = 0;
    let вес = 0;
    for (let i = 3, п = 0; i < data.length; i += 4, п += 1) {
      const альфа = data[i];
      if (альфа === 0) continue;
      сумма += (п % холст.width) * альфа;
      вес += альфа;
    }
    return вес === 0 ? null : сумма / вес / холст.width;
  }, фигура);
  if (доля === null) {
    провал('правило 15', 'центр массы марки не замерился: холст пустой');
    return null;
  }
  return доля * МАРКА.ширина;
})();

