/**
 * Разбор `Record<Ключ, 'путь'>` из исходника.
 *
 * Регулярка, а не импорт: `.astro` Node не выполняет, а тянуть сюда сборщик
 * Astro ради тридцати строк — это зависимость, которая переживёт свою пользу.
 * Не нашлось ни одной пары — сборка падает: значит файл переписали, и витрина
 * молча показала бы вчерашний набор.
 *
 * **Ключ, выпавший из разбора поодиночке, до 2026-08-20 не ловил никто.**
 * Регулярка берёт только литерал, а путь, вынесенный в константу над картой
 * (`tv: TV`), ей не пара — и три телевизора отсутствовали в ките всё время, что
 * они делили рисунок. Падало бы только полное «ни одной пары»; таблица в README
 * при этом говорила «30». Поэтому ключи считаются дважды: сколько строк вида
 * `ключ:` в блоке и сколько из них разобралось. Разошлось — сборка встала и
 * назвала выпавшие.
 */
function разобратьПути(исходник, начало) {
  const блок = исходник.slice(исходник.indexOf(начало));
  const конец = блок.indexOf('\n};');
  const тело = конец === -1 ? блок : блок.slice(0, конец);
  const пары = [...тело.matchAll(/^\s*([A-Za-zА-Яа-я0-9_]+):\s*'([^']+)',/gm)];
  const всеКлючи = [...тело.matchAll(/^\s{2}([A-Za-zА-Яа-я0-9_]+):/gm)].map(([, к]) => к);
  const карта = pairsToMap(пары);
  const выпали = всеКлючи.filter((ключ) => !карта.has(ключ));
  if (выпали.length > 0) {
    throw new Error(
      `${начало}: ключи не разобрались и выпали бы из витрины молча: ${выпали.join(', ')}`,
    );
  }
  return карта;
}
function pairsToMap(пары) {
  const карта = new Map();
  for (const [, ключ, значение] of пары) {
    if (значение.startsWith('M') || значение.startsWith('m')) карта.set(ключ, значение);
  }
  return карта;
}

