/* Правила 13 и 14: контрасты иконок приложений. Считаются здесь, а не глазами:
   разница между 2,65 и 3,56 на картинке не видна, а порог проходит только
   вторая. Формула — WCAG 2.1, та же, что в `scripts/бренд-контрасты.py`. */
function светимость(hex) {
  const к = hex.replace('#', '').match(/../g).map((п) => {
    const v = parseInt(п, 16) / 255;
    return v <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * к[0] + 0.7152 * к[1] + 0.0722 * к[2];
}
function контраст(a, b) {
  const [я, б] = [светимость(a), светимость(b)];
  return (Math.max(я, б) + 0.05) / (Math.min(я, б) + 0.05);
}

