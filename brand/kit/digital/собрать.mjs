/**
 * Иконка приложения: марка на скруглённом квадрате.
 *
 * Поле вокруг марки — один диаметр головы, ровно правило охранного поля из
 * раздела 01 брендбука. Скругление 0,2 стороны: у Telegram аватар всё равно
 * обрежется в круг, а у иконки на телефоне углы скругляет система, — но файл,
 * открытый в редакторе, должен выглядеть иконкой, а не квадратом с фигурой.
 */
function иконкаПриложения({ сторона, фон, цветТела, цветГоловы }, центрМассы = null) {
  if (!МАРКА) return '';
  const поле = 2 * МАРКА.r;
  const доступно = МАРКА.высота + 2 * поле;
  const масштаб = сторона / доступно;
  // По центру массы, если он замерен, и по рамке — пока не замерен (первый
  // проход, которым он и меряется).
  const центр = центрМассы ?? МАРКА.ширина / 2;
  const сдвигX = сторона / 2 - центр * масштаб;
  const сдвигY = поле * масштаб;

  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${сторона} ${сторона}" width="${сторона}" height="${сторона}" role="img" aria-label="Fixli">
  <title>Fixli</title>
  <rect width="${сторона}" height="${сторона}" rx="${(сторона * 0.2).toFixed(1)}" fill="${фон}" />
  <g transform="translate(${сдвигX.toFixed(2)} ${сдвигY.toFixed(2)}) scale(${масштаб.toFixed(4)})">
    <circle cx="${МАРКА.cx}" cy="${МАРКА.cy}" r="${МАРКА.r}" fill="${цветГоловы}" />
    <path fill="${цветТела}" d="${МАРКА.d}" />
  </g>
</svg>`;
}

