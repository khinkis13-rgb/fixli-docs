#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Диверсии для сборщика печатных макетов наклеек.

ЗАЧЕМ
-----
Сторож, который ни разу не падал, охраняет пустоту. В этом проекте таких нашли
семь штук, и каждый выглядел работающим. Поэтому каждая проверка в
`печать-наклеек.mjs` подтверждается подменой, которая обязана её уронить.

ПОЧЕМУ PYTHON, А НЕ SHELL
-------------------------
Дважды подряд (31.08 и 02.09) диверсии писались на shell с кириллическими
именами переменных, и ни bash, ни zsh их не берут: присваивание молча не
происходит, сравнение пустых строк печатает «поймана» на каждой подмене, а
подмены при этом остаются в исходнике. Здесь восстановление идёт в `finally`.

ЧТО ПРОВЕРЯЕТСЯ ПОМИМО КОДА ВОЗВРАТА
------------------------------------
Что сторож НАЗЫВАЕТ причину. Диверсия, уронившая сборку чужим падением,
считается непойманной: человек в журнале получит не ту причину и пойдёт чинить
не то. Это правило записано 14.09 после сторожа, падавшего необработанным
ENOENT.

Запуск: python3 brand/kit/transport/диверсии-наклеек.py
"""

import pathlib
import subprocess
import sys

ЗДЕСЬ = pathlib.Path(__file__).resolve().parent
КОРЕНЬ = ЗДЕСЬ.parent.parent.parent
СБОРЩИК = ЗДЕСЬ / "печать-наклеек.mjs"
ТЗ = ЗДЕСЬ / "тз-оклейка.md"
ЗНАК = КОРЕНЬ / "brand" / "знак" / "fixli-знак.svg"

ДИВЕРСИИ = [
    (
        "триада возвращена на место с носителя — туда, где на неё налезает адрес",
        ТЗ,
        "| «КАЧЕСТВО · ОТВЕТСТВЕННОСТЬ · РЕЗУЛЬТАТ» | 1,34 × 0,034 H | 1,235 H | 0,89 H |",
        "| «КАЧЕСТВО · ОТВЕТСТВЕННОСТЬ · РЕЗУЛЬТАТ» | 1,34 × 0,034 H | 0,81 H | 0,89 H |",
        "наложение на борту",
    ),
    (
        "марка отодвинута от кормы так, что налезает на адрес",
        ТЗ,
        "| Марка: голова и тело | 0,42 × 1,20 H | 0,085 H | 0,03 H |",
        "| Марка: голова и тело | 0,42 × 1,20 H | 0,30 H | 0,03 H |",
        "наложение на борту",
    ),
    (
        "требование к длине панели занижено до 2,20 H",
        ТЗ,
        "нижняя строка просит не меньше 2,60 H.",
        "нижняя строка просит не меньше 2,20 H.",
        "ТЗ занижает требование к панели",
    ),
    (
        "в знаке подменён фирменный оранжевый на близкий, но чужой",
        ЗНАК,
        '#f38025',
        '#f47f2a',
        "краска мимо токена",
    ),
    (
        "блок услуг съезжает вправо на 4 мм — артворк вылезает за холст",
        СБОРЩИК,
        "текстВ(пос.у.слово, п.кегль, п.трекинг, иконка + зазор + п.лево,",
        "текстВ(пос.у.слово, п.кегль, п.трекинг, иконка + зазор + п.лево + 4,",
        "чернила не равны габариту",
    ),
    (
        "зеркальная марка перестала быть зеркальной",
        СБОРЩИК,
        'нутро: `<g transform="translate(${маркаШирина.toFixed(4)} 0) scale(-1 1)">',
        'нутро: `<g transform="translate(0 0) scale(1 1)">',
        "зеркало не зеркало",
    ),
    (
        "у одной наклейки убрано латинское имя для архива",
        СБОРЩИК,
        "'марка-зеркало': 'mark-mirrored',",
        "",
        "нет латинского имени",
    ),
]


def прогон(ключи=()):
    из = subprocess.run(
        ["node", str(СБОРЩИК), *ключи], cwd=КОРЕНЬ, capture_output=True, text=True
    )
    return из.returncode, (из.stdout + из.stderr)


def главное():
    код, вывод = прогон()
    if код != 0:
        print("✗ Сборка не проходит ДО диверсий — чинить надо её, а не сторожей:\n" + вывод)
        return 1

    поймано = 0
    for имя, файл, было, стало, ожидаемая_причина in ДИВЕРСИИ:
        исходное = файл.read_text(encoding="utf-8")
        if было not in исходное:
            print(f"⚠ «{имя}»: якорь подмены не найден в {файл.name} — диверсия устарела")
            continue
        try:
            файл.write_text(исходное.replace(было, стало, 1), encoding="utf-8")
            код, вывод = прогон()
            назвал = ожидаемая_причина in вывод
            if код != 0 and назвал:
                поймано += 1
                print(f"✓ поймана: {имя}\n    сторож сказал: «{ожидаемая_причина}»")
            elif код != 0:
                print(f"✗ УПАЛО НЕ ТЕМ: {имя}\n    ждали «{ожидаемая_причина}», а вывод другой:\n"
                      + "\n".join("      " + с for с in вывод.strip().splitlines()[-6:]))
            else:
                print(f"✗ ПРОШЛА ЗЕЛЁНОЙ: {имя} — сторожа на это нет")
        finally:
            файл.write_text(исходное, encoding="utf-8")

    # короткая машина приходит ключом, а не правкой файла 
    код, вывод = прогон(["--панель=3000"])
    всего = len(ДИВЕРСИИ) + 1
    if код != 0 and "раскладка длиннее панели" in вывод:
        поймано += 1
        print("✓ поймана: панель короче раскладки (--панель=3000)\n    сторож сказал: «раскладка длиннее панели»")
    else:
        print("✗ ПРОШЛА ЗЕЛЁНОЙ: панель короче раскладки")

    print(f"\nПоймано {поймано} из {всего}")
    код, _ = прогон()
    if код != 0:
        print("✗ После восстановления сборка не проходит — исходники не вернулись на место")
        return 1
    return 0 if поймано == всего else 1


if __name__ == "__main__":
    sys.exit(главное())
