    ш: м.actualBoundingBoxLeft + м.actualBoundingBoxRight,
    в: м.actualBoundingBoxAscent + м.actualBoundingBoxDescent,
    лево: м.actualBoundingBoxLeft, верх: м.actualBoundingBoxAscent,
