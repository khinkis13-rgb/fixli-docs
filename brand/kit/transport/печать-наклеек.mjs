/**
 * Печатные макеты наклеек на фургон: то, что уезжает в типографию, а не схема.
 *
 * ── Зачем отдельный сборщик, если есть `собрать.mjs` ─────────────────────
 * `png/борт.png` — ЧЕРТЁЖ: панель, кабина, юбка, выноски, доли H. Его читают
 * глазами, чтобы понять раскладку. Печатать с него нельзя: там есть всё, кроме
 * того, что должно лечь на кузов. Ровно эта путаница уже стоила одного круга
 * с цехом по футболкам (14.09.2026): им ушёл чертёж, они попросили макет.
 *
 * Здесь — АРТВОРК: каждая наклейка отдельным файлом, в натуральную величину,
 * на прозрачном фоне, текст в кривых.
 *
 * ── Откуда числа ─────────────────────────────────────────────────────────
 * Доли H читаются из `тз-оклейка.md` при каждом запуске, и ТЗ там ИСТОЧНИК, а
 * не копия: разошлось — сборка падает. Миллиметры появляются умножением на
 * размеры конкретной машины, которые приходят ключами:
 *
 *   node brand/kit/transport/печать-наклеек.mjs --H=1400 --панель=3640 --Ш=1565 --кабина=1700
 *
 *   --H       высота панели борта: от верхней кромки до верха молдинга-юбки
 *   --панель  длина панели борта: от стойки за дверью кабины до заднего угла
 *   --Ш       ширина задних дверей
 *   --кабина  ширина кабины на высоте знака над лобовым стеклом
 *
 * ── Почему H по умолчанию 1400, а не замер ───────────────────────────────
 * Замерить может только тот, кто стоит у машины. Вывести H из рендера заказчика
 * нельзя: у него перспектива (ширина кузова на виде сзади растёт с 202 px
 * вверху до 265 внизу), абсолютных размеров он не несёт. 1400 — не выдумка
 * этого файла: оно уже стоит примером пересчёта в ТЗ и средним из трёх типовых
 * высот в `замеры.md`. Для СРАВНЕНИЯ ЦЕН точность H не важна — типография
 * считает по квадратуре, и ошибка одинакова у всех подрядчиков. Для РЕЗКИ
 * важна, поэтому пересчёт — одна команда, а просьба замерить стоит первой
 * строкой в сообщении заказчику.
 *
 * ── Почему главный файл вектор, а не 300 ppi ─────────────────────────────
 * 300 ppi на знаке 1414 мм — это 16 700 × 7 200 пикселей, 120 мегапикселей.
 * Столько не нужно ни одному широкоформатному принтеру (на метровой наклейке
 * рабочая плотность 100–150 ppi) и не влезает в холст браузера: предел 16 384.
 * Поэтому PNG здесь — превью и контрольный лист, а печатают с PDF в кривых.
 * Фактическая плотность каждого PNG печатается в сопроводиловке числом.
 *
 * ── Что здесь проверяется, чего не проверял чертёж ───────────────────────
 * Наложения. На чертеже весь текст рисуется одним кеглем 30 px, поэтому
 * настоящих ширин строк там нет вовсе и столкнуться им негде. В натуральную
 * величину адрес сайта и триада накладывались на 476 мм — это нашлось здесь и
 * починено в ТЗ. Сторож остаётся: любые два элемента борта, чьи рамки
 * пересеклись, роняют сборку.
 *
 * Запуск: node brand/kit/transport/печать-наклеек.mjs
 */

