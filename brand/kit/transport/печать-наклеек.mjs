/* ─── 12. Монтажная схема борта ───────────────────────────────────────────
 *
 * Это ЧЕРТЁЖ, и он подписан чертежом. Нужен он затем, что комплект отдельных
 * наклеек без схемы — это мешок плёнки: монтажник не знает, на каком расстоянии
 * от заднего угла что клеить.
 */
{
  const S = 2400 / ПАНЕЛЬ;                      // масштаб чертежа
  /* Ниже панели надо оставить место телу фигуры: оно уходит под молдинг, и в
   * первой редакции его срезало краем холста — на схеме это выглядело как
   * решение «обрезать фигуру по юбке», которого никто не принимал. */
  const свес = Math.max(...бортовые.map((н) => н.место.верх + н.в - H), 0);
  const подпанель = (свес + 60) * S;
  const полеСл = 60, полеСв = 90;
  const легендаВ = 30 + Math.ceil(бортовые.length / 2) * 30 + 60;
  const холстШ = ПАНЕЛЬ * S + полеСл * 2;
  const холстВ = полеСв + H * S + подпанель + легендаВ;
  const вx = (отКормы) => полеСл + (ПАНЕЛЬ - отКормы) * S;   // корма справа, как на чертежах кита
  const вy = (отКромки) => полеСв + отКромки * S;

  const порядок = [...бортовые].sort((а, б) => а.место.край - б.место.край);
  const блоки = порядок.map((н) => {
    const x = вx(н.место.край + н.ш), y = вy(н.место.верх);
    return `<image href="data:image/png;base64,${readFileSync(join(ВЫХОД, `fixli-${н.имя}.png`)).toString('base64')}"
      x="${x.toFixed(2)}" y="${y.toFixed(2)}" width="${(н.ш * S).toFixed(2)}" height="${(н.в * S).toFixed(2)}"/>`;
  }).join('\n');

  /* Номер у элемента, расшифровка — в легенде. Подписи прямо у элементов в
   * первой редакции налезли друг на друга в кашу: на борту семь наклеек, и
   * четыре из них стоят в одной трети длины. */
  const метки = порядок.map((н, i) => {
    /* Метка ставится ЗА рамкой элемента, по диагонали вверх-влево: в первой
     * редакции она стояла внутри и садилась прямо на букву — номер элемента
     * закрывал собой то, на что указывает. */
    const цx = Math.max(16, вx(н.место.край + н.ш) - 15);
    const цy = Math.max(16, вy(н.место.верх) - 15);
    return `<circle cx="${цx.toFixed(2)}" cy="${цy.toFixed(2)}" r="13" fill="#12438F" stroke="#ffffff" stroke-width="2"/>
      <text x="${цx.toFixed(2)}" y="${(цy + 5).toFixed(2)}" text-anchor="middle" font-family="Rubik" font-size="15" font-weight="700" fill="#ffffff">${i + 1}</text>`;
  }).join('\n');

  const легенда = порядок.map((н, i) => {
    const колонка = i % 2, ряд = Math.floor(i / 2);
    const x = полеСл + колонка * (ПАНЕЛЬ * S / 2);
    const y = полеСв + H * S + подпанель + 24 + ряд * 30;
    return `<circle cx="${(x + 11).toFixed(2)}" cy="${(y - 5).toFixed(2)}" r="11" fill="#12438F"/>
      <text x="${(x + 11).toFixed(2)}" y="${(y).toFixed(2)}" text-anchor="middle" font-family="Rubik" font-size="14" font-weight="700" fill="#ffffff">${i + 1}</text>
      <text x="${(x + 32).toFixed(2)}" y="${(y).toFixed(2)}" font-family="Rubik" font-size="17" fill="#22303f">${н.имя} — ${мм(н.ш)} × ${мм(н.в)} мм · ${мм(н.место.край)} мм от угла, ${мм(н.место.верх)} мм от кромки</text>`;
  }).join('\n');

  const юбкаВ = 90 * S;
  const чертёж = `
    <rect x="${полеСл}" y="${полеСв}" width="${(ПАНЕЛЬ * S).toFixed(2)}" height="${(H * S).toFixed(2)}" fill="#ffffff" stroke="#8b97a6" stroke-width="2"/>
    <rect x="${полеСл}" y="${(полеСв + H * S).toFixed(2)}" width="${(ПАНЕЛЬ * S).toFixed(2)}" height="${юбкаВ.toFixed(2)}" fill="#dfe3e8" stroke="#8b97a6" stroke-width="1"/>
    <text x="${полеСл + 10}" y="${(полеСв + H * S + юбкаВ / 2 + 6).toFixed(2)}" font-family="Rubik" font-size="16" fill="#5b6672">молдинг-юбка</text>
    <text x="${(полеСл + ПАНЕЛЬ * S).toFixed(2)}" y="${полеСв - 18}" text-anchor="end" font-family="Rubik" font-size="18" fill="#12438F">кормовой угол ↓</text>
    <text x="${полеСл}" y="${полеСв - 18}" font-family="Rubik" font-size="18" fill="#5b6672">← к кабине</text>
    ${блоки}
    ${метки}
    <text x="${полеСл}" y="${(полеСв + H * S + подпанель - 26).toFixed(2)}" font-family="Rubik" font-size="20" font-weight="700" fill="#12438F">Монтажная схема ЛЕВОГО борта · H = ${H} мм, длина панели ${ПАНЕЛЬ} мм. Правый борт — зеркальная копия целиком.</text>
    <text x="${полеСл}" y="${(полеСв + H * S + подпанель - 4).toFixed(2)}" font-family="Rubik" font-size="16" fill="#8a3b0b">Это схема, а не макет для печати: печатают с отдельных файлов наклеек. Все расстояния — от КОРМОВОГО угла.</text>
    ${легенда}`;
  const лист4 = await печатный.newPage();
  await лист4.setContent(`<!doctype html><meta charset="utf-8"><style>${СТИЛЬ}body{background:#eef1f5}</style>
    <svg xmlns="http://www.w3.org/2000/svg" width="${холстШ.toFixed(0)}" height="${холстВ.toFixed(0)}" viewBox="0 0 ${холстШ.toFixed(0)} ${холстВ.toFixed(0)}">${чертёж}</svg>`);
  await лист4.evaluate(() => document.fonts.ready);
  await лист4.setViewportSize({ width: Math.ceil(холстШ), height: Math.ceil(холстВ) });
  await лист4.screenshot({ path: join(ВЫХОД, 'монтаж-борт.png') });
  await лист4.close();
}

