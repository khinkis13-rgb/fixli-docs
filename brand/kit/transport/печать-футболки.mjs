/**
 * Печатные макеты формы бригады: то, что уезжает в цех, а не схема для чтения.
 *
 * ── Зачем отдельный сборщик, если есть `собрать.mjs` ─────────────────────
 * `png/футболка.png` — ЧЕРТЁЖ: силуэт футболки, выноски, размеры, подписи. Его
 * читают глазами, чтобы понять, что и куда наносится. Печатать с него нельзя:
 * в файле есть всё, кроме того, что должно лечь на ткань.
 *
 * Здесь — АРТВОРК: ровно те чернила, что попадут на футболку, в натуральную
 * величину, на прозрачном фоне. Ни выносок, ни рамок, ни силуэта.
 *
 * ── Что просит цех и чем мы отвечаем ─────────────────────────────────────
 * Требования поставщика (2026-09-17): 300 DPI, CMYK, желательно вектор,
 * PDF или PNG с прозрачным фоном, в нужном размере.
 *
 *  · 300 DPI      — PNG отдаётся ровно в 300 ppi, и плотность записана в сам
 *                   файл (pHYs), иначе цех откроет его как 72 ppi и увидит
 *                   размер втрое больше заданного;
 *  · вектор       — PDF, и текст в нём переведён В КРИВЫЕ. Шрифта Rubik у цеха
 *                   нет; вшитый в PDF сабсет переживает не каждый RIP, а кривые
 *                   не подставляются ничем;
 *  · прозрачный   — и PDF, и PNG. Фон ткани тёмно-синий, белого поля под
 *                   графикой быть не должно;
 *  · нужный размер— страница PDF равна габариту печати (285 × 194 мм на спине),
 *                   поэтому «печать 100 %» даёт ровно заданные миллиметры;
 *  · CMYK         — отдельным файлом. И вот тут есть оговорка, которую нельзя
 *                   пропустить, см. ниже.
 *
 * ── Оговорка про CMYK и белый, ради которой написан этот комментарий ──────
 * В CMYK белого не существует: 0/0/0/0 — это «не печатать ничего». На белой
 * бумаге так и нужно, на тёмно-синей ткани это пустое место. Белая часть знака
 * и обе строки печатаются БЕЛОЙ КРАСКОЙ — отдельной, пятой: у DTF это штатный
 * белый слой, у шелкографии отдельная форма. Поэтому:
 *
 *   · главный файл для DTF — PNG с прозрачным фоном: непрозрачный пиксель =
 *     краска, и белый в нём остаётся белым;
 *   · CMYK-PDF отдаётся для совместимости с требованием. Оранжевый в нём
 *     переведён в CMYK честно, белый остался белым объектом (DeviceGray 1);
 *   · превью на синем кладётся в комплект НЕ для печати, а чтобы цех не решил,
 *     что файл пустой: белая графика на прозрачном фоне в любом просмотрщике
 *     выглядит как пустой лист.
 *
 * ── Откуда числа ─────────────────────────────────────────────────────────
 * Из таблицы раздела 3 `тз-спецодежда.md`, и они там ИСТОЧНИК, а не копия:
 * скрипт парсит ТЗ и падает, если расходится хоть одно. Дублировать числа в
 * коде нельзя — в этом проекте копия числа уже расходилась с оригиналом молча.
 *
 * ── Как размер задан ─────────────────────────────────────────────────────
 * Обязательное число — ШИРИНА строки, а не высота букв: «высота» читается
 * тремя способами и расходится на 41 % (разбор — в ТЗ). Кегль здесь не задан
 * вовсе, он ПОДБИРАЕТСЯ под заданную ширину чернил и печатается в отчёте.
 *
 * ── Чем это собрано и почему не библиотекой ──────────────────────────────
 * Браузер + Ghostscript, оба уже в системе. Растровой библиотеки (sharp,
 * ImageMagick) в проекте нет ни одной, и заводить её ради двух картинок
 * незачем: Chromium отдаёт PNG нужного размера сам, если поднять ему
 * `deviceScaleFactor`, а плотность в файл дописывается чанком `pHYs` в
 * девять байт. Замер готового PNG идёт там же, в браузере, по пикселям.
 *
 * Запуск: node brand/kit/transport/печать-футболки.mjs
 */

