/* Кадр снимается с запасом и режется до пикселя уже в браузере.
 *
 * Причина — в самом Chromium: `clip` он округляет ВНИЗ до целых CSS-пикселей,
 * а уже потом умножает на плотность. У груди высота 147,52 CSS-пикселя
 * превращалась в 147, и файл выходил 459 пикселей вместо 461 — то есть знаку
 * срезало 0,2 мм снизу при полностью исправной разметке. Целое число получалось
 * бы только при размерах, кратных 25 пикселям (это 2,1 мм), а подгонять
 * миллиметры макета под арифметику скриншотилки — значит менять печать под
 * инструмент. Поэтому снимаем заведомо больше и обрезаем холстом. */
const снять = async ({ ш, в, нутро, фон, путь, прозрачно, wPx, hPx }) => {
  const лист = прозрачно ? листПечати : листПревью;
  const множитель = прозрачно ? МАСШТАБ : 1;
  const целевойW = wPx ?? Math.round(ш * множитель * 96 / ММ_В_ДЮЙМЕ);
  const целевойH = hPx ?? Math.round(в * множитель * 96 / ММ_В_ДЮЙМЕ);
  const cssШ = Math.ceil(целевойW / множитель) + 1;
  const cssВ = Math.ceil(целевойH / множитель) + 1;
  await лист.setContent(полотно(ш, в, нутро, фон));
  await лист.evaluate(() => document.fonts.ready);
  await лист.setViewportSize({ width: cssШ + 2, height: cssВ + 2 });
  const сырой = await лист.screenshot({ type: 'png', omitBackground: Boolean(прозрачно),
    clip: { x: 0, y: 0, width: cssШ, height: cssВ } });
  const base64 = await лист.evaluate(async ({ данные, W, H }) => {
    const img = new Image();
    img.src = `data:image/png;base64,${данные}`;
    await img.decode();
    const c = document.createElement('canvas');
    c.width = W; c.height = H;
    c.getContext('2d').drawImage(img, 0, 0);
    return c.toDataURL('image/png').split(',')[1];
  }, { данные: сырой.toString('base64'), W: целевойW, H: целевойH });
  const буфер = Buffer.from(base64, 'base64');
  if (путь) writeFileSync(путь, буфер);
  return буфер;
};

/* Замер идёт по пикселям готового файла: где чернила, какой они ширины, какие
 * между ними зазоры и какого они цвета. Полоса — это связная группа строк, в
 * которых есть хоть один непрозрачный пиксель. */
const замерить = async (буферИлиПуть) => {
  const данные = (Buffer.isBuffer(буферИлиПуть) ? буферИлиПуть : readFileSync(буферИлиПуть)).toString('base64');
  return листПревью.evaluate(async ({ данные, порог }) => {
    const img = new Image();
    img.src = `data:image/png;base64,${данные}`;
    await img.decode();
    const c = document.createElement('canvas');
    c.width = img.naturalWidth; c.height = img.naturalHeight;
    const ctx = c.getContext('2d', { willReadFrequently: true });
    ctx.drawImage(img, 0, 0);
    const W = c.width, H = c.height;
    const d = ctx.getImageData(0, 0, W, H).data;

    const занята = new Array(H).fill(false);
    for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) {
      if (d[(y * W + x) * 4 + 3] > порог) { занята[y] = true; break; }
    }
    const куски = [];
    let старт = null;
    for (let y = 0; y <= H; y++) {
      if (занята[y]) { if (старт === null) старт = y; }
      else if (старт !== null) { куски.push([старт, y - 1]); старт = null; }
    }
    const полосы = куски.map(([в0, в1]) => {
      let x0 = W, x1 = -1;
      for (let y = в0; y <= в1; y++) for (let x = 0; x < W; x++) {
        if (d[(y * W + x) * 4 + 3] > порог) { if (x < x0) x0 = x; if (x > x1) x1 = x; }
      }
      return { верх: в0, низ: в1, лево: x0, право: x1 };
    });

    const цвета = new Map();
    let прозрачных = 0;
    for (let i = 0; i < d.length; i += 4) {
      if (d[i + 3] === 0) { прозрачных++; continue; }
      if (d[i + 3] < 250) continue;
      const ц = `${d[i]},${d[i + 1]},${d[i + 2]}`;
      цвета.set(ц, (цвета.get(ц) ?? 0) + 1);
    }
    return { W, H, полосы, доляПрозрачных: прозрачных / (W * H),
      цвета: [...цвета].sort((a, b) => b[1] - a[1]).slice(0, 8) };
  }, { данные, порог: 8 });
};

/* ─── 6. Подгонка спины ───────────────────────────────────────────────────*/
const вмм = (px) => px / ПКС;
/* Предел точности здесь не наш выбор, а разрешение самого замера: при 300 ppi
 * один пиксель — это 0,085 мм, и требовать сходимости лучше него бессмысленно.
 * 0,13 мм — полтора пикселя; на строке в 285 мм это 0,05 % и вчетверо меньше
 * того, что различает рулетка цеха. */
const ТОЧНОСТЬ = 0.13; // мм

const спина = {
  знак: { ширина: ЧИСЛА.знакСпина, x: (ЧИСЛА.блокШирина - ЧИСЛА.знакСпина) / 2, y: 0 },
  телефон: { кегль: телефон.кегль, x: 0, база: 0 },
  адрес: { кегль: адрес.кегль, x: 0, база: 0 },
};
/* Стартовые координаты — расчётные, дальше их правит замер. */
{
  const вЗнака = знакВысотаПри(спина.знак.ширина);
  const общая = вЗнака + ЧИСЛА.телефонОтступ + телефон.высота + ЧИСЛА.адресОтступ + адрес.высота;
  const поле = (ЧИСЛА.блокВысота - общая) / 2;
  спина.знак.y = поле;
  спина.телефон.x = (ЧИСЛА.блокШирина - телефон.ширина) / 2 - телефон.левыйВынос;
  спина.телефон.база = поле + вЗнака + ЧИСЛА.телефонОтступ + телефон.надБазой;
  спина.адрес.x = (ЧИСЛА.блокШирина - адрес.ширина) / 2 - адрес.левыйВынос;
  спина.адрес.база = спина.телефон.база - телефон.надБазой + телефон.высота + ЧИСЛА.адресОтступ + адрес.надБазой;
}

const нутроСпины = () => [
  знакВ(спина.знак.ширина, спина.знак.x, спина.знак.y),
  текстВ(ТЕЛЕФОН, спина.телефон.кегль, спина.телефон.x, спина.телефон.база, '#ffffff'),
  текстВ(АДРЕС, спина.адрес.кегль, спина.адрес.x, спина.адрес.база, '#ffffff'),
].join('\n');

let сошлось = false;
let последнийЗамерСпины = null;
for (let проход = 1; проход <= 8 && !сошлось; проход++) {
  const кадр = await снять({ ш: ЧИСЛА.блокШирина, в: ЧИСЛА.блокВысота, нутро: нутроСпины(), прозрачно: true });
  const з = await замерить(кадр);
  последнийЗамерСпины = з;
  if (з.полосы.length !== 3) { беда('раскладка спины', `полос чернил ${з.полосы.length}, а должно быть три`); break; }
  const [зн, тел, адр] = з.полосы;
  const ширина = (п) => вмм(п.право - п.лево + 1);
  const центр = (п) => вмм((п.лево + п.право + 1) / 2 - з.W / 2);

  const промахи = [
    Math.abs(ширина(зн) - ЧИСЛА.знакСпина), Math.abs(ширина(тел) - ЧИСЛА.телефонШирина),
    Math.abs(ширина(адр) - ЧИСЛА.адресШирина), Math.abs(центр(зн)), Math.abs(центр(тел)), Math.abs(центр(адр)),
    Math.abs(вмм(тел.верх - зн.низ - 1) - ЧИСЛА.телефонОтступ),
    Math.abs(вмм(адр.верх - тел.низ - 1) - ЧИСЛА.адресОтступ),
    Math.abs(вмм(зн.верх) - вмм(з.H - адр.низ - 1)),
  ];
  сошлось = Math.max(...промахи) <= ТОЧНОСТЬ;
  if (сошлось) break;

  /* Ширина — множителем: чернила масштабируются линейно вместе с кеглем. */
  спина.знак.ширина *= ЧИСЛА.знакСпина / ширина(зн);
  спина.телефон.кегль *= ЧИСЛА.телефонШирина / ширина(тел);
  спина.адрес.кегль *= ЧИСЛА.адресШирина / ширина(адр);
  /* Горизонталь — сдвигом на промах: центруем по чернилам, а не по
   * `text-anchor`, потому что трекинг добавляется и после последнего знака и
   * уводит «середину» на его половину. Эта грабля уже срезала букву на крыше. */
  спина.знак.x -= центр(зн);
  спина.телефон.x -= центр(тел);
  спина.адрес.x -= центр(адр);
  /* Вертикаль: сначала выставляем заданные отступы, потом весь блок целиком
   * центруем в холсте — поля сверху и снизу должны быть равны. */
  const вЗнака = вмм(зн.низ - зн.верх + 1);
  const вТел = вмм(тел.низ - тел.верх + 1);
  const вАдр = вмм(адр.низ - адр.верх + 1);
  const поле = (ЧИСЛА.блокВысота - (вЗнака + ЧИСЛА.телефонОтступ + вТел + ЧИСЛА.адресОтступ + вАдр)) / 2;
  const цельВерхЗнака = поле;
  const цельВерхТел = поле + вЗнака + ЧИСЛА.телефонОтступ;
  const цельВерхАдр = цельВерхТел + вТел + ЧИСЛА.адресОтступ;
  спина.знак.y += цельВерхЗнака - вмм(зн.верх);
  спина.телефон.база += цельВерхТел - вмм(тел.верх);
  спина.адрес.база += цельВерхАдр - вмм(адр.верх);
}
if (!сошлось) беда('подгонка спины', 'за восемь проходов размеры не сошлись в 0,05 мм');

/* ─── 7. Подгонка груди ───────────────────────────────────────────────────*/
const грудь = { ширина: ЧИСЛА.знакГрудь, x: 0, y: 0 };
const грудьВысотаХолста = знакВысотаПри(ЧИСЛА.знакГрудь);
const грудьWpx = Math.round(ЧИСЛА.знакГрудь * ПКС);
const грудьHpx = Math.round(грудьВысотаХолста * ПКС);
const нутроГруди = () => знакВ(грудь.ширина, грудь.x, грудь.y);

let грудьСошлась = false;
for (let проход = 1; проход <= 8 && !грудьСошлась; проход++) {
  const кадр = await снять({ ш: ЧИСЛА.знакГрудь, в: грудьВысотаХолста, нутро: нутроГруди(),
    прозрачно: true, wPx: грудьWpx, hPx: грудьHpx });
  const з = await замерить(кадр);
  if (з.полосы.length !== 1) { беда('раскладка груди', `полос чернил ${з.полосы.length}, а должна быть одна`); break; }
  const п = з.полосы[0];
  const ширина = вмм(п.право - п.лево + 1);
  const сдвигX = вмм((п.лево + п.право + 1) / 2 - з.W / 2);
  const сдвигY = вмм((п.верх + п.низ + 1) / 2 - з.H / 2);
  грудьСошлась = Math.abs(ширина - ЧИСЛА.знакГрудь) <= ТОЧНОСТЬ && Math.abs(сдвигX) <= ТОЧНОСТЬ && Math.abs(сдвигY) <= ТОЧНОСТЬ;
  if (грудьСошлась) break;
  грудь.ширина *= ЧИСЛА.знакГрудь / ширина;
  грудь.x -= сдвигX;
  грудь.y -= сдвигY;
}
if (!грудьСошлась) беда('подгонка груди', 'за восемь проходов знак не сошёлся в 0,05 мм');

/* ─── 8. Выпуск файлов ────────────────────────────────────────────────────*/
if (existsSync(ВЫХОД)) rmSync(ВЫХОД, { recursive: true });
mkdirSync(ВЫХОД, { recursive: true });

/* Плотность в PNG: Chromium её не пишет вовсе, а без неё цех откроет 3366 px
 * как 72 ppi и увидит лист 1,19 метра шириной вместо 285 мм. Чанк `pHYs` —
 * девять байт: пикселей на метр по X и по Y плюс признак единицы. */
const таблицаCRC = (() => {
  const т = new Int32Array(256);
  for (let n = 0; n < 256; n++) { let c = n; for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1; т[n] = c; }
  return т;
})();
const crc32 = (буфер) => {
  let c = 0xffffffff;
  for (const байт of буфер) c = таблицаCRC[(c ^ байт) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
};
const вписатьПлотность = (путь, dpi) => {
  const байты = readFileSync(путь);
  const наМетр = Math.round(dpi / 0.0254);
  const данные = Buffer.alloc(9);
  данные.writeUInt32BE(наМетр, 0); данные.writeUInt32BE(наМетр, 4); данные.writeUInt8(1, 8);
  const тело = Buffer.concat([Buffer.from('pHYs', 'latin1'), данные]);
  const длина = Buffer.alloc(4); длина.writeUInt32BE(9, 0);
  const сумма = Buffer.alloc(4); сумма.writeUInt32BE(crc32(тело), 0);
  const место = байты.indexOf(Buffer.from('IDAT', 'latin1')) - 4;
  if (место < 4) { беда('PNG', `${путь.split('/').pop()}: не найден IDAT, плотность не записана`); return; }
  writeFileSync(путь, Buffer.concat([байты.subarray(0, место), длина, тело, сумма, байты.subarray(место)]));
};

const МАКЕТЫ = [
  { имя: 'спина', ш: ЧИСЛА.блокШирина, в: ЧИСЛА.блокВысота, нутро: нутроСпины(),
    wPx: Math.round(ЧИСЛА.блокШирина * ПКС), hPx: Math.round(ЧИСЛА.блокВысота * ПКС), полос: 3 },
  { имя: 'грудь', ш: ЧИСЛА.знакГрудь, в: грудьВысотаХолста, нутро: нутроГруди(),
    wPx: грудьWpx, hPx: грудьHpx, полос: 1 },
];

const собранные = [];
for (const макет of МАКЕТЫ) {
  const база = join(ВЫХОД, `fixli-футболка-${макет.имя}`);

  await листПечати.setContent(полотно(макет.ш, макет.в, макет.нутро, null));
  await листПечати.evaluate(() => document.fonts.ready);
  const сырой = `${база}-сырой.pdf`;
  await листПечати.pdf({ path: сырой, width: `${макет.ш}mm`, height: `${макет.в}mm`, printBackground: true,
    margin: { top: 0, bottom: 0, left: 0, right: 0 }, pageRanges: '1' });

  /* Кривые и точный медиабокс. `-dNoOutputFonts` превращает текст в контуры:
   * шрифта Rubik у цеха нет, а подстановка чужого меняет ширину строки — то
   * самое число, которое цех обязан воспроизвести рулеткой. */
  const общее = ['-dNoOutputFonts', '-dFIXEDMEDIA',
    `-dDEVICEWIDTHPOINTS=${pt(макет.ш).toFixed(4)}`, `-dDEVICEHEIGHTPOINTS=${pt(макет.в).toFixed(4)}`];
  гс(['-q', '-o', `${база}.pdf`, '-sDEVICE=pdfwrite', ...общее, сырой]);
  гс(['-q', '-o', `${база}-CMYK.pdf`, '-sDEVICE=pdfwrite', ...общее,
    '-sColorConversionStrategy=CMYK', '-dProcessColorModel=/DeviceCMYK', сырой]);
  rmSync(сырой);

  const файлPNG = `${база}-${DPI}dpi.png`;
  await снять({ ...макет, путь: файлPNG, прозрачно: true });
  вписатьПлотность(файлPNG, DPI);

  /* Превью на синем — НЕ для печати. Без него белая графика на прозрачном фоне
   * в любом просмотрщике выглядит пустым файлом, и это готовый повод для
   * звонка «вы прислали пустоту». Поле 20 мм, чтобы было видно, что не обрез. */
  const поле = 20;
  await снять({ ш: макет.ш + поле * 2, в: макет.в + поле * 2,
    нутро: `<g transform="translate(${поле} ${поле})">${макет.нутро}</g>`,
    фон: '#12438F', путь: `${база}-превью-на-ткани.png`, прозрачно: false });

  собранные.push({ макет, база, файлPNG });
}

/* ─── 9. Проверки готовых файлов ──────────────────────────────────────────
 *
 * Меряется ВЫХОД, а не разметка: подрядчик получает файлы, а не исходник, и
 * все прошлые дефекты носителей этого проекта жили ровно в зазоре между тем,
 * что объявлено в коде, и тем, что вышло в файле.
 */
const ДОПУСК = 0.2; // мм

for (const { макет, база, файлPNG } of собранные) {
  const з = await замерить(файлPNG);
  if (з.W !== макет.wPx || з.H !== макет.hPx) {
    беда('размер PNG', `${макет.имя}: ${з.W}×${з.H} px при ожидаемых ${макет.wPx}×${макет.hPx}`);
  }
  /* Прозрачность проверяется долей пустого поля, а не углами: у груди холст
   * обрезан ровно по чернилам, и угловой пиксель там законно занят знаком. */
  if (з.доляПрозрачных < 0.05) {
    беда('прозрачность PNG', `${макет.имя}: прозрачных пикселей ${(з.доляПрозрачных * 100).toFixed(1)} % — фон не пустой`);
  }
  const байты = readFileSync(файлPNG);
  const место = байты.indexOf(Buffer.from('pHYs', 'latin1'));
  const ppi = место > 0 ? Math.round(байты.readUInt32BE(место + 4) * 0.0254) : 0;
  if (ppi !== DPI) беда('плотность PNG', `${макет.имя}: ${ppi} ppi вместо ${DPI}`);

  /* На ткань идут ровно два цвета. Третий крупной площадью означает, что в
   * макет заехала посторонняя краска; полупрозрачные кромки сглаживания сюда
   * не попадают — они отсеяны порогом непрозрачности. */
  const свой = (ц) => {
    const [r, g, b] = ц.split(',').map(Number);
    if (r === 255 && g === 255 && b === 255) return true;
    return Math.abs(r - 243) <= 2 && Math.abs(g - 128) <= 2 && Math.abs(b - 37) <= 2;
  };
  const чужие = з.цвета.filter(([ц, n]) => !свой(ц) && n > 200);
  if (чужие.length) беда('посторонний цвет', `${макет.имя}: ${чужие.map(([ц, n]) => `${ц} (${n} px)`).join(', ')}`);

  if (з.полосы.length !== макет.полос) {
    беда('полосы чернил', `${макет.имя}: ${з.полосы.length} вместо ${макет.полос}`);
  } else if (макет.имя === 'спина') {
    const [зн, тел, адр] = з.полосы;
    const ширина = (п) => вмм(п.право - п.лево + 1);
    const проверить = (что, факт, цель) => {
      if (Math.abs(факт - цель) > ДОПУСК) беда('замер', `спина · ${что}: ${факт.toFixed(2)} мм вместо ${цель} мм`);
    };
    проверить('ширина знака', ширина(зн), ЧИСЛА.знакСпина);
    проверить('ширина телефона', ширина(тел), ЧИСЛА.телефонШирина);
    проверить('ширина адреса', ширина(адр), ЧИСЛА.адресШирина);
    проверить('отступ знак → телефон', вмм(тел.верх - зн.низ - 1), ЧИСЛА.телефонОтступ);
    проверить('отступ телефон → адрес', вмм(адр.верх - тел.низ - 1), ЧИСЛА.адресОтступ);
    проверить('поле сверху против поля снизу', вмм(зн.верх), вмм(з.H - адр.низ - 1));
    for (const [что, п] of [['знак', зн], ['телефон', тел], ['адрес', адр]]) {
      const сдвиг = вмм((п.лево + п.право + 1) / 2 - з.W / 2);
      if (Math.abs(сдвиг) > ДОПУСК) беда('центровка', `спина · ${что}: сдвиг ${сдвиг.toFixed(2)} мм от оси`);
    }
    ФАКТ.спина = {
      знак: ширина(зн), телефон: ширина(тел), адрес: ширина(адр),
      высотаЗнака: вмм(зн.низ - зн.верх + 1), цифры: вмм(тел.низ - тел.верх + 1), адресВысота: вмм(адр.низ - адр.верх + 1),
    };
  } else {
    const п = з.полосы[0];
    const ширина = вмм(п.право - п.лево + 1);
    if (Math.abs(ширина - ЧИСЛА.знакГрудь) > ДОПУСК) {
      беда('замер', `грудь · ширина знака: ${ширина.toFixed(2)} мм вместо ${ЧИСЛА.знакГрудь} мм`);
    }
    ФАКТ.грудь = { знак: ширина, высота: вмм(п.низ - п.верх + 1) };
  }

  /* PDF: одна страница, точный размер, ни одного шрифта. */
  for (const файл of [`${база}.pdf`, `${база}-CMYK.pdf`]) {
    const имяФайла = файл.split('/').pop();
    const инфо = execFileSync('pdfinfo', [файл], { encoding: 'utf8' });
    const страниц = Number(инфо.match(/Pages:\s+(\d+)/)?.[1]);
    if (страниц !== 1) беда('страниц в PDF', `${имяФайла}: ${страниц}`);
    const размер = инфо.match(/Page size:\s+([\d.]+) x ([\d.]+)/);
    const дШ = Math.abs(Number(размер[1]) - pt(макет.ш)) / 72 * ММ_В_ДЮЙМЕ;
    const дВ = Math.abs(Number(размер[2]) - pt(макет.в)) / 72 * ММ_В_ДЮЙМЕ;
    if (дШ > 0.12 || дВ > 0.12) беда('размер страницы PDF', `${имяФайла}: расхождение ${дШ.toFixed(2)} × ${дВ.toFixed(2)} мм`);
    const шрифты = execFileSync('pdffonts', [файл], { encoding: 'utf8' }).trim().split('\n').slice(2).filter(Boolean);
    if (шрифты.length) беда('шрифт в PDF', `${имяФайла}: ${шрифты.length} шт. — текст не переведён в кривые`);
  }
}

await браузер.close();

/* ─── 10. Итог ────────────────────────────────────────────────────────────*/
if (беды.length) {
  console.error('\n✗ Макеты собраны, но проверки не прошли:\n' + беды.map((б) => '  · ' + б).join('\n'));
  process.exit(1);
}

