console.log(`  спина  ${ЧИСЛА.блокШирина} × ${ЧИСЛА.блокВысота} мм · ${Math.round(ЧИСЛА.блокШирина * ПКС)} × ${Math.round(ЧИСЛА.блокВысота * ПКС)} px при ${DPI} ppi`);
console.log(`  грудь  ${ЧИСЛА.знакГрудь} × ${грудьВысотаХолста.toFixed(1)} мм · ${грудьWpx} × ${грудьHpx} px`);
console.log(`  замер выхода: знак ${ФАКТ.спина.знак.toFixed(2)} мм, телефон ${ФАКТ.спина.телефон.toFixed(2)} мм, адрес ${ФАКТ.спина.адрес.toFixed(2)} мм`);
console.log(`  высота чернил: знак ${ФАКТ.спина.высотаЗнака.toFixed(1)} мм, цифры ${ФАКТ.спина.цифры.toFixed(1)} мм, адрес ${ФАКТ.спина.адресВысота.toFixed(1)} мм`);
console.log(`  кегль под заданную ширину: телефон ${спина.телефон.кегль.toFixed(2)} мм, адрес ${спина.адрес.кегль.toFixed(2)} мм`);
