/**
 * Сборка схем транспорта и спецодежды: проверка документа и экспорт чертежей в PNG.
 *
 * Зачем PNG, если есть HTML: оклейщик и швейник не открывают репозиторий. Им
 * уходит картинка в WhatsApp и распечатка на A4, и она обязана быть ровно тем
 * же, что в документе, — поэтому её не рисуют руками, а снимают с него.
 *
 * ── Что проверяется ПЕРЕД съёмкой ────────────────────────────────────────
 * Десять правил. Первые четыре — общие для носителей бренда, остальные шесть
 * появились из-за того, что схема уезжает подрядчику и ошибка в ней стоит
 * плёнки и партии футболок:
 *
 *  1. литерал цвета в CSS — значение живёт один раз, в `brand/tokens.css`;
 *  2. физическое свойство вместо логического — документ читают и справа налево;
 *  3. обещания: каждый ключ `data-обещание` есть в `реестр-обещаний.md` и не
 *     помечен там красным;
 *  4. стоп-слова в отрисованном тексте — страховка, гарантия, 24/7, скидка,
 *     хранение вещей;
 *  5. знак не растянут: рамка каждого <image> держит пропорцию файла;
 *  6. знак нужного размера: внутри файла знака есть поля (содержимое
 *     414,3 × 179,8 в рамке 436 × 198), поэтому <image> рисует его на 5 %
 *     мельче рамки. Атрибут `data-знак` объявляет ширину САМОГО знака, и она
 *     сверяется с расчётной. Без этой проверки схема врала: на борту знак
 *     выходил 912 единиц вместо заявленных 1013, то есть подрядчик получил бы
 *     знак на 10 % меньше, чем на трёх ездящих машинах;
 *  7. на схемах транспорта нет `fixli-марка*.svg`. Фигура на борту — та же
 *     буква `i`, что в знаке (замер 2026-08-31: оранжевый круг это голова, она
 *     стоит ровно над телом, правые кромки совпадают, пропорция 0,35), но
 *     нарисована она ДВУМЯ слоями с разными классами, потому что чертёж сверяет
 *     цвет каждого слоя с его токеном. Подстановка одного файла-марки сломала бы
 *     восьмое правило и заодно потеряла бы посадку головы относительно тела;
 *  8. цвет каждого слоя чертежа равен назначенному ему токену — то же правило,
 *     что поймало серые надписи в рекламных креативах;
 *  9. на 375 px нет горизонтальной прокрутки: схему открывают с телефона в
 *     мастерской;
 * 10. в разметке нет мёртвого кегля: атрибут `font-size` у подписи ничего не
 *     задаёт, его перебивает CSS. Девятнадцать чисел от 26 до 110 не делали
 *     ничего — текст рисовался единым кеглем, и обе стороны мерили разное.
 *     Размер объявляют выносной размер и таблица ТЗ;
 * 11. промпт генератора знает те же числа: каждое число из таблицы нанесения
 *     `тз-спецодежда.md` обязано найтись в `brand/claude-design.md`. Проверяется
 *     вхождение, а не совпадение — ТЗ источник, промпт копия, движение
 *     одностороннее. Без этого генерация воспроизвела бы старое число, и макап
 *     заспорил бы с документом (наши 390 против 391 разошлись за час);
 * 12. все четыре соседних файла направления на месте и ссылки на них живые.
 *
 * Запуск: node brand/kit/transport/собрать.mjs [папка]
 */
import { existsSync, mkdirSync, readFileSync, rmSync, statSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { chromium } from '@playwright/test';

const ЗДЕСЬ = dirname(fileURLToPath(import.meta.url));
const СТРАНИЦА = join(ЗДЕСЬ, 'схемы.html');
const СТИЛИ = join(ЗДЕСЬ, 'схемы.css');
const РЕЕСТР = join(ЗДЕСЬ, 'реестр-обещаний.md');
const выход = process.argv[2] ?? join(ЗДЕСЬ, 'png');

/* Содержимое внутри `fixli-знак.svg`: 414,3 × 179,8 при рамке 436 × 198.
   Отсюда доля 0,9502 — на неё умножается ширина <image>, чтобы получить
   ширину самого знака. Измеряется getBBox, см. правило 6. */
const ДОЛЯ_ЗНАКА = 414.3 / 436;
const ПРОПОРЦИЯ_ФАЙЛА = 436 / 198;

const СТОП_СЛОВА = [
  'страховк', 'застрахован', 'гарантир', 'гарантия', '24/7', 'круглосуточ',
  'скидк', 'хранение', 'фиксированная цена',
  /* «Хендлинг» — не смягчение запрета, а слово, которого у компании нет вовсе:
     его придумал генератор на макетах крыши 2026-08-31 и поставил в блок услуг
     вместо «хендимен». Здесь же короткое «хранение»: до 2026-09-01 запрет стоял
     формой «хранение вещей», и ровно эту короткую генератор нарисовал как
     законную пятую услугу — сторож бы её пропустил. Обе формы на носителе
     невозможны законно: в блоке услуг стоит `услуги.четыре`. */
  'хендлинг',
  /* Служебный адрес сайта и второй домен. Плёнка живёт годами, и адрес,
     который не открывается, дороже здесь, чем на любом другом носителе.
     Боевой `fixlihome.co.il` печатать можно — он отвечает с 18 августа. */
  'pages.dev', 'fixligroup',
];

/* Слой чертежа → токен, которым он обязан быть залит */
const СЛОИ = [
  { класс: 'круг', токен: '--fx-orange', свойство: 'fill' },
  { класс: 'фигура', токен: '--fx-navy', свойство: 'fill' },
  { класс: 'плашка', токен: '--fx-navy', свойство: 'fill' },
  { класс: 'ткань', токен: '--fx-navy', свойство: 'fill' },
  { класс: 'подпись--знак', токен: '--fx-navy', свойство: 'fill' },
  { класс: 'подпись--выворотка', токен: '--fx-white', свойство: 'fill' },
  { класс: 'подпись--размер', токен: '--fx-orange-text', свойство: 'fill' },
  { класс: 'подпись--размер-выворотка', токен: '--fx-white', свойство: 'fill' },
  { класс: 'размер--выворотка', токен: '--fx-white', свойство: 'stroke' },
  /* Адрес сайта. Строка появилась 2026-08-19 и сначала не попала в эту
     таблицу — то есть её цвет не проверялся ничем. Ровно этот зазор между
     «написано в CSS» и «получилось на экране» и породил девятое правило
     рекламного кита, где все 24 креатива вышли с серыми надписями. */
  { класс: 'подпись--сайт', токен: '--fx-orange-text', свойство: 'fill' },
];

const СОСЕДИ = ['замеры.md', 'реестр-обещаний.md', 'тз-оклейка.md', 'тз-спецодежда.md'];

const беды = [];
const беда = (правило, текст) => беды.push(`${правило}: ${текст}`);

/* ─── 1. Литералы цвета в CSS ────────────────────────────────────────────── */
const css = readFileSync(СТИЛИ, 'utf8');
const безКомментариев = css.replace(/\/\*[\s\S]*?\*\//g, '');
for (const строка of безКомментариев.split('\n')) {
  const литерал = строка.match(/#[0-9a-fA-F]{3,8}\b|\brgba?\(|\bhsla?\(/);
  if (литерал) беда('цвет литералом', `${строка.trim()} — значение живёт в brand/tokens.css`);
}

/* ─── 2. Физические свойства ─────────────────────────────────────────────── */
const ФИЗИЧЕСКИЕ = /(^|[\s;{])(margin-(left|right)|padding-(left|right)|border-(left|right)(-[a-z]+)?|(^|[^-])\bleft|right)\s*:/;
for (const строка of безКомментариев.split('\n')) {
  if (ФИЗИЧЕСКИЕ.test(строка) && !/inset-inline|border-inline/.test(строка)) {
    беда('физическое свойство', `${строка.trim()} — нужно логическое (inline-start/end)`);
  }
}

/* ─── Реестр обещаний ────────────────────────────────────────────────────── */
const реестр = readFileSync(РЕЕСТР, 'utf8');
const разрешены = new Set();
const запрещены = new Set();
for (const строка of реестр.split('\n')) {
  const ключ = строка.match(/^\|\s*`([^`]+)`\s*\|/);
  if (!ключ) continue;
  // в какой таблице стоит строка, определяет ближайший заголовок выше
  const позиция = реестр.indexOf(строка);
  const выше = реестр.slice(0, позиция);
  const последний = выше.lastIndexOf('## ');
  const заголовок = реестр.slice(последний, последний + 60);
  if (заголовок.includes('🔴')) запрещены.add(ключ[1]);
  else разрешены.add(ключ[1]);
}

/* ─── Браузер ────────────────────────────────────────────────────────────── */
const браузер = await chromium.launch();
const страница = await браузер.newPage({
  viewport: { width: 1400, height: 1000 },
  deviceScaleFactor: 2,
});
await страница.goto(pathToFileURL(СТРАНИЦА).href);
await страница.waitForTimeout(500);

/* ─── 3. Обещания ────────────────────────────────────────────────────────── */
const ключи = await страница.$$eval('[data-обещание]', (узлы) =>
  узлы.map((у) => ({ ключ: у.dataset.обещание, текст: у.textContent.trim().slice(0, 60) })));
for (const { ключ, текст } of ключи) {
  if (запрещены.has(ключ)) беда('запрещённое обещание', `${ключ} помечен 🔴: «${текст}»`);
  else if (!разрешены.has(ключ)) беда('обещание вне реестра', `${ключ} — «${текст}»`);
}

/* ─── 4. Стоп-слова в отрисованном тексте ────────────────────────────────── */
/* Ищем только внутри чертежей: в тексте документа «страховки нет» — это разбор
   запрета, а не обещание, и ловить его нельзя. */
const наНосителях = (await страница.$$eval('.чертёж svg', (узлы) =>
  узлы.map((у) => у.textContent.toLowerCase()).join(' ')));
for (const слово of СТОП_СЛОВА) {
  if (наНосителях.includes(слово)) беда('стоп-слово на носителе', слово);
}

/* ─── 5, 6, 7. Знак ──────────────────────────────────────────────────────── */
const знаки = await страница.$$eval('.чертёж image', (узлы) =>
  узлы.map((у) => ({
    href: у.getAttribute('href'),
    w: parseFloat(у.getAttribute('width')),
    h: parseFloat(у.getAttribute('height')),
    объявлено: у.dataset.знак ? parseFloat(у.dataset.знак) : null,
    transform: у.getAttribute('transform') ?? '',
  })));

if (знаки.length === 0) беда('знак', 'на схемах не найдено ни одного знака');

for (const з of знаки) {
  if (/марка/.test(з.href)) {
    беда('марка на транспорте',
      `${з.href} — фигура на борту рисуется двумя слоями (круг-голова и контур тела), а не одним файлом`);
  }
  const пропорция = з.w / з.h;
  if (Math.abs(пропорция - ПРОПОРЦИЯ_ФАЙЛА) / ПРОПОРЦИЯ_ФАЙЛА > 0.01) {
    беда('знак растянут', `${з.href}: рамка ${з.w}×${з.h} = ${пропорция.toFixed(3)}, у файла ${ПРОПОРЦИЯ_ФАЙЛА.toFixed(3)}`);
  }
  if (/scale\(\s*-/.test(з.transform)) беда('знак зеркалится', з.href);
  if (з.объявлено === null) {
    беда('знак без data-знак', `${з.href}: не объявлена ширина самого знака`);
  } else {
    const фактически = з.w * ДОЛЯ_ЗНАКА;
    const отклонение = Math.abs(фактически - з.объявлено) / з.объявлено;
    if (отклонение > 0.02) {
      беда('знак не того размера',
        `${з.href}: объявлено ${з.объявлено}, рисуется ${фактически.toFixed(0)} (внутри файла поля)`);
    }
  }
}

/* ─── 8. Цвет слоёв ──────────────────────────────────────────────────────── */
for (const слой of СЛОИ) {
  const проверка = await страница.evaluate(({ класс, токен, свойство }) => {
    const узел = document.querySelector(`.${CSS.escape(класс)}`);
    if (!узел) return { нет: true };
    const факт = getComputedStyle(узел)[свойство];
    const проба = document.createElement('span');
    document.body.appendChild(проба);
    проба.style.color = `var(${токен})`;
    const ожидание = getComputedStyle(проба).color;
    проба.remove();
    return { факт, ожидание };
  }, слой);
  if (проверка.нет) беда('слой не найден', слой.класс);
  else if (проверка.факт !== проверка.ожидание) {
    беда('цвет слоя', `.${слой.класс}: ${проверка.факт}, а токен ${слой.токен} даёт ${проверка.ожидание}`);
  }
}

/* ─── 9. Центровка блока на спине футболки ───────────────────────────────
 *
 * Дефект нашли глаза Дмитрия 2026-09-01, а замер назвал его величину: телефон
 * стоял на 27,7 мм левее центра корпуса при знаке и адресе по центру. Причина
 * была в выключке — у текстов не было `text-anchor`, то есть `x` означал левый
 * край, и центровку подгоняли шириной строки на глаз. Достаточно поменять
 * шрифт или номер, чтобы она уехала снова, поэтому сторож меряет не координаты
 * в разметке, а **отрисованные** центры.
 */
const центрыСпины = await страница.evaluate(() => {
  const блок = [...document.querySelectorAll('.чертёж')].find((д) => д.dataset['имя'] === 'футболка');
  if (!блок) return null;
  const svg = блок.querySelector('svg');
  const узлы = [...svg.querySelectorAll('text, image')];
  const центр = (у) => { const b = у.getBBox(); return b.x + b.width / 2; };
  const текст = (нужно) => узлы.find((у) => (у.textContent ?? '').includes(нужно));
  const знак = svg.querySelector('image[data-знак="260"]');
  const собрать = {};
  for (const [имя, узел] of Object.entries({
    знак,
    телефон: текст('055-294'),
    сайт: текст('fixlihome'),
    выноска: текст('260 мм'),
  })) собрать[имя] = узел ? центр(узел) : null;
  return собрать;
});
if (!центрыСпины) {
  беда('чертёж футболки', 'не найден — центровку спины проверить нечем');
} else {
  // Корпус спины объявлен в самом чертеже: M960 350 … L1480 950.
  const ЦЕНТР_СПИНЫ = (960 + 1480) / 2;
  const ДОПУСК = 2;
  for (const [имя, центр] of Object.entries(центрыСпины)) {
    if (центр === null) { беда('элемент спины', `${имя}: не найден в чертеже`); continue; }
    const сдвиг = центр - ЦЕНТР_СПИНЫ;
    if (Math.abs(сдвиг) > ДОПУСК) {
      беда('центровка спины',
        `${имя}: центр ${центр.toFixed(1)} против ${ЦЕНТР_СПИНЫ} у корпуса — сдвиг ${сдвиг.toFixed(1)} мм`);
    }
  }
}

/* ─── 10. Прокрутка на телефоне ──────────────────────────────────────────── */
await страница.setViewportSize({ width: 375, height: 800 });
await страница.waitForTimeout(200);
const прокрутка = await страница.evaluate(() =>
  document.documentElement.scrollWidth - document.documentElement.clientWidth);
if (прокрутка > 0) беда('горизонтальная прокрутка', `${прокрутка} px на 375`);
await страница.setViewportSize({ width: 1400, height: 1000 });
await страница.waitForTimeout(200);

/*
 * ─── 10. Мёртвый кегль в разметке ────────────────────────────────────────
 *
 * Атрибут `font-size` на `<text>` в этих схемах не работает: в `схемы.css`
 * стоит `.подпись { font-size: 30px }`, а правило CSS сильнее презентационного
 * атрибута. До 2026-08-19 таких атрибутов было девятнадцать, со значениями от
 * 26 до 110, и **ни одно из них ничего не делало** — весь текст на всех пяти
 * чертежах рисовался одним кеглем.
 *
 * Стоило это дорого и дважды. Сначала я поставил адрес сайта «мельче номера»,
 * посмотрел на PNG и принял иерархию, которой не существовало. Потом мы с
 * соседним чатом разошлись в замере строки телефона вдвое — он мерил высоту
 * знаков, я кегль, и сверить нас было не по чему, потому что кегль в файле был
 * фикцией.
 *
 * Размеры нанесения живут не в разметке, а в таблицах ТЗ: на кузове в долях H,
 * на одежде в миллиметрах. Схема — чертёж, и величину на нём объявляет выносной
 * размер, а не то, каким кеглем нарисована подпись. Поэтому атрибут запрещён
 * целиком: число, которое ничего не меняет, читается как решение.
 */
const мёртвыйКегль = await страница.$$eval('.чертёж svg text[font-size]', (узлы) =>
  узлы.map((у) => `${у.textContent.trim().slice(0, 24)} → font-size="${у.getAttribute('font-size')}"`));
for (const случай of мёртвыйКегль) {
  беда('мёртвый кегль', `${случай}: CSS его перебивает. Размер объявляется выносным размером и таблицей ТЗ`);
}

/*
 * ─── 11. Промпт генератора знает те же числа, что ТЗ ─────────────────────
 *
 * Числа нанесения живут в `тз-спецодежда.md`, и только там. Но их вторая,
 * буквальная копия есть в `brand/claude-design.md`: рантайм генерации макапов
 * наших файлов не читает вовсе — в промпт число попадает текстом или не
 * попадает никак. Ссылку на строку таблицы туда не поставить.
 *
 * Копия без сторожа расходится молча, и это не гипотеза: за один день телефон
 * оказался 390 мм в таблице и 391 мм в промпте. Миллиметр никому не мешает —
 * ровно так это всегда и начинается.
 *
 * Правило одностороннее: **ТЗ — источник, промпт — копия**. Поэтому проверяется
 * не совпадение двух файлов, а вхождение: каждое число из таблицы обязано
 * найтись в промпте. Лишние числа в промпте не запрещены — там есть и отступы,
 * и посадка, которых в этой таблице нет.
 *
 * Сторож стоит в сборке транспорта намеренно: она запускается при любой правке
 * носителя, то есть ровно тогда, когда число и меняют.
 */
const ПРОМПТ = join(ЗДЕСЬ, '..', '..', 'claude-design.md');
if (!existsSync(ПРОМПТ)) {
  беда(
    'нет файла промптов',
    'brand/claude-design.md не найден. Он переехал — поправьте путь здесь, иначе числа ТЗ и промпта разойдутся молча',
  );
} else {
  const тз = readFileSync(join(ЗДЕСЬ, 'тз-спецодежда.md'), 'utf8');
  const промпт = readFileSync(ПРОМПТ, 'utf8');
  /* Из таблицы нанесения берутся сами числа с единицей: и ширины строк, и
     размеры знака. Разбирается та же строка, что читает швейник, — отдельного
     машинного формата не заводим по тому же правилу, что у реестра обещаний. */
  const строкиТаблицы = тз
    .split('\n')
    .filter((с) => с.startsWith('| Спина |') || с.startsWith('| Перёд |'));
  const числа = new Set();
  for (const с of строкиТаблицы) {
    for (const м of с.matchAll(/(\d+)\s*мм/g)) числа.add(`${м[1]} мм`);
  }
  if (числа.size === 0) {
    беда('таблица нанесения', 'в тз-спецодежда.md не разобрано ни одного числа — сломался формат');
  }
  for (const число of числа) {
    /* Пробел в промпте может быть неразрывным — сравниваем по цифре и единице. */
    const [цифра] = число.split(' ');
    const есть = new RegExp(`(?<!\\d)${цифра}\\s*мм`).test(промпт);
    if (!есть) {
      беда(
        'промпт отстал от ТЗ',
        `${число} есть в таблице нанесения тз-спецодежда.md, но нет в brand/claude-design.md. Генерация воспроизведёт старое число, и макап заспорит с документом`,
      );
    }
  }
}

/* ─── 12. Соседние файлы ─────────────────────────────────────────────────── */
for (const файл of СОСЕДИ) {
  if (!existsSync(join(ЗДЕСЬ, файл))) беда('нет файла направления', файл);
}
const ссылки = await страница.$$eval('a[href$=".md"]', (узлы) => узлы.map((у) => у.getAttribute('href')));
for (const ссылка of new Set(ссылки)) {
  if (!existsSync(join(ЗДЕСЬ, ссылка))) беда('битая ссылка', ссылка);
}

/* ─── Итог проверок ──────────────────────────────────────────────────────── */
if (беды.length > 0) {
  await браузер.close();
  console.error(`\nСхемы не собраны, нарушений: ${беды.length}\n`);
  for (const б of беды) console.error('  ✗ ' + б);
  console.error('');
  process.exit(1);
}

/* ─── Экспорт ────────────────────────────────────────────────────────────── */
rmSync(выход, { recursive: true, force: true });
mkdirSync(выход, { recursive: true });

const чертежи = страница.locator('.чертёж[data-имя]');
const сколько = await чертежи.count();
for (let i = 0; i < сколько; i++) {
  const узел = чертежи.nth(i);
  const имя = await узел.getAttribute('data-имя');
  const путь = join(выход, `${имя}.png`);
  await узел.locator('svg').screenshot({ path: путь });
  /* Пустой экспорт весит единицы килобайт: так выглядит снимок чертежа, у
     которого не отрисовался ни знак, ни слои. Молчаливая пустышка уехала бы
     подрядчику как схема. */
  const вес = statSync(путь).size;
  if (вес < 10_000) {
    console.error(`\n  ✗ ${имя}.png весит ${вес} байт — чертёж не отрисовался\n`);
    await браузер.close();
    process.exit(1);
  }
  console.log(`  ✓ ${имя}.png — ${(вес / 1024).toFixed(0)} КБ`);
}

await браузер.close();
console.log(`\nПроверок пройдено: 13. Схем снято: ${сколько} → ${выход}\n`);
