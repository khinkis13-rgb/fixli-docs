/**
 * Разбирает фотокреативы на два слоя: кадр и плашку с текстом.
 *
 * Зачем. Готовый PNG — это наша композиция: где стоит плашка, что она собой
 * закрывает и что остаётся видно. Решение это хорошее ровно до тех пор, пока
 * кадр один; на живом креативе с телевизором оно уже сместилось (плашка
 * переехала снизу вверх, потому что внизу был подвесной комод, а сверху пустая
 * стена). Слоями композицию собирает человек, глядя на конкретный кадр.
 *
 * Что важно знать, собирая руками:
 *
 * 1. **Плашка снимается со своим фоном и скруглением, вокруг — прозрачность.**
 *    Полупрозрачной подложки у неё нет намеренно: контраст к фотографии
 *    посчитать нельзя, он свой в каждой точке кадра, поэтому текст живёт на
 *    сплошном тёмно-синем. Не делайте её полупрозрачной в редакторе — это
 *    единственное, что здесь запрещено.
 * 2. **Поле у краёв кадра — 80 px** при ширине 1080 (`--fx-ad-pad`). Плашка
 *    уже собрана по этой сетке: её ширина 920 px, то есть ровно между полями.
 * 3. **Охранное поле знака внутри плашки уже соблюдено** — трогать внутренние
 *    отступы не нужно, а вот масштабировать плашку целиком можно свободно.
 * 4. У сторис сверху 160 px и снизу 260 px занимает обвязка площадки: всё,
 *    что туда попадёт, будет перекрыто аватаром и строкой ответа.
 *
 * Опись пар пишется рядом: какая плашка к какому кадру и где она стояла у нас.
 *
 * Запуск: node brand/kit/ads/разобрать-на-слои.mjs
 */

import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { chromium } from '@playwright/test';

const ЗДЕСЬ = dirname(fileURLToPath(import.meta.url));
const СТРАНИЦА = join(ЗДЕСЬ, 'креативы.html');
const ВЫХОД = join(ЗДЕСЬ, 'слои');

/* Имя пары читается без описи: `<сюжет>-<формат>-<язык>--фон` и `--плашка`.
   Отсюда же берётся человеческая подпись для описи. */
/* Кадр у русской и ивритской версии один и тот же файл — он снимается один раз
   на формат, а плашек к нему две. Возить один и тот же снимок дважды значит
   завести две правды об одном кадре: поправят одну, забудут другую. */
const МАКЕТЫ = [
  { id: '14-упаковка-ru', фон: 'упаковка-4x5', имя: 'упаковка-4x5-ru', о: 'Упаковка, лента 4:5' },
  { id: '14-упаковка-he', фон: 'упаковка-4x5', имя: 'упаковка-4x5-he', о: 'Упаковка, лента 4:5, иврит' },
  { id: '15-сторис-упаковка-ru', фон: 'упаковка-9x16', имя: 'упаковка-9x16-ru', о: 'Упаковка, сторис 9:16' },
  { id: '15-сторис-упаковка-he', фон: 'упаковка-9x16', имя: 'упаковка-9x16-he', о: 'Упаковка, сторис 9:16, иврит' },
  { id: '16-телевизор-фото-ru', фон: 'телевизор-1x1', имя: 'телевизор-1x1-ru', о: 'Телевизор, лента 1:1' },
  { id: '16-телевизор-фото-he', фон: 'телевизор-1x1', имя: 'телевизор-1x1-he', о: 'Телевизор, лента 1:1, иврит' },
];

const снятые_фоны = new Set();

rmSync(ВЫХОД, { recursive: true, force: true });
mkdirSync(ВЫХОД, { recursive: true });

const браузер = await chromium.launch();
const стр = await браузер.newPage({
  viewport: { width: 1800, height: 2000 },
  deviceScaleFactor: 1,
});

try {
  await стр.goto(pathToFileURL(СТРАНИЦА).href);
  await стр.evaluate(() => {
    document.body.dataset.режим = 'экспорт';
  });
  await стр.evaluate(() => document.fonts.ready);
  await стр.evaluate(() =>
    Promise.all([...document.images].map((и) => и.decode().catch(() => undefined))),
  );

  const строки = [];
  for (const макет of МАКЕТЫ) {
    const кр = стр.locator(`article[id="${макет.id}"]`);
    const плита = кр.locator('.кр-плита');

    /* Где плашка стоит у нас — в координатах холста, от его левого верхнего
       угла. Человек, собирающий руками, может повторить нашу композицию
       ровно или отступить от неё сознательно. */
    const место = await кр.evaluate((узел) => {
      const х = узел.getBoundingClientRect();
      const п = узел.querySelector('.кр-плита').getBoundingClientRect();
      return {
        холст: `${Math.round(х.width)} × ${Math.round(х.height)}`,
        плашка: `${Math.round(п.width)} × ${Math.round(п.height)}`,
        x: Math.round(п.left - х.left),
        y: Math.round(п.top - х.top),
        сверху: п.top - х.top < х.bottom - п.bottom,
      };
    });

    /* Кадр без плашки: прячем её на время съёмки. Снимаем сам холст, поэтому
       размер слоя совпадает с форматом площадки — накладывать можно без
       подгонки. */
    if (!снятые_фоны.has(макет.фон)) {
      await плита.evaluate((узел) => {
        узел.style.visibility = 'hidden';
      });
      await кр.screenshot({ path: join(ВЫХОД, `${макет.фон}--фон.png`) });
      await плита.evaluate((узел) => {
        узел.style.visibility = '';
      });
      снятые_фоны.add(макет.фон);
    }

    /* Плашка отдельно: `omitBackground` убирает всё вокруг неё, включая
       прозрачные уголки скругления. Свой тёмно-синий фон у плашки остаётся —
       он часть её, а не подложка страницы. */
    await плита.screenshot({
      path: join(ВЫХОД, `${макет.имя}--плашка.png`),
      omitBackground: true,
    });

    строки.push(
      `| ${макет.о} | \`${макет.фон}--фон.png\` | \`${макет.имя}--плашка.png\` | ${место.холст} | ${место.плашка} | ${место.x}, ${место.y} | ${место.сверху ? 'сверху' : 'снизу'} |`,
    );
    console.log(`${макет.имя} — кадр ${макет.фон}--фон.png ${место.холст}, плашка ${место.плашка} в (${место.x}, ${место.y})`);
  }

  writeFileSync(
    join(ВЫХОД, 'опись.md'),
    [
      '# Слои фотокреативов: кадр отдельно, плашка отдельно',
      '',
      'Собрано `node brand/kit/ads/разобрать-на-слои.mjs`. Пара читается по имени:',
      'плашка называется как её кадр плюс язык. Кадров три, плашек шесть — снимок',
      'у русской и ивритской версии один и тот же, меняется только текст.',
      '',
      '| Что | Кадр | Плашка | Размер кадра | Размер плашки | Где стояла (x, y) | Край |',
      '|---|---|---|---|---|---|---|',
      ...строки,
      '',
      '**Координаты — от левого верхнего угла кадра**, в пикселях самого файла.',
      'Это наша композиция, а не обязательство: плашку можно двигать, ориентируясь',
      'на то, что она не должна закрывать.',
      '',
      '**Что плашка не должна закрывать в каждом кадре:**',
      '',
      '- **упаковка** — синие одеяла и стрейч поверх них: в этом весь смысл кадра,',
      '  он доказывает строку «плёнка поверх одеяла, а не вместо него». Низ (пол)',
      '  и верх (тёмная витрина) свободны;',
      '- **телевизор** — сам телевизор и просвет под ним: он показывает, что тот',
      '  **висит**, а не стоит. Пустая стена сверху свободна, комод внизу можно',
      '  закрывать — там же стоит и наша плашка.',
      '',
      '**Три правила, которые в редакторе легко нарушить:**',
      '',
      '1. плашку **не делать полупрозрачной** — контраст к фотографии не считается,',
      '   он свой в каждой точке кадра, поэтому фон под текстом сплошной;',
      '2. плашку можно двигать и масштабировать целиком, но **не растягивать по одной',
      '   оси** — знак внутри неё нельзя искажать (раздел 01 брендбука);',
      '3. поле у краёв кадра — **80 px** при ширине 1080; плашка собрана по этой',
      '   сетке, её ширина 920.',
      '',
      '**У сторис** сверху 160 px и снизу 260 px закрывает обвязка площадки —',
      'аватар с подписью и строка ответа.',
      '',
    ].join('\n'),
    'utf8',
  );
} finally {
  await браузер.close();
}

console.log(`\nГотово: ${снятые_фоны.size} кадра и ${МАКЕТЫ.length} плашек в ${ВЫХОД.slice(ЗДЕСЬ.length + 1)}/`);
