try {
  await стр.goto(pathToFileURL(СТРАНИЦА).href);
  await стр.evaluate(() => {
    document.body.dataset.режим = 'экспорт';
  });
  await стр.evaluate(() => document.fonts.ready);
  await стр.evaluate(() =>
    Promise.all([...document.images].map((и) => и.decode().catch(() => undefined))),
  );

  const проверка = await стр.evaluate(
    ({ ОХРАННОЕ_ПОЛЕ, МИНИМУМ_ЗНАКА, СТОП_СЛОВА, ЦВЕТА_СЛОЁВ, КАДРЫ }) => {
      const беды = [];
      const креативы = [];

      /* Токен → «rgb(r, g, b)», в том же виде, в каком его отдаёт
         getComputedStyle: сравнивать строки надёжнее, чем парсить обратно. */
      const корень = getComputedStyle(document.documentElement);
      const токен = (имя) => {
        const hex = корень.getPropertyValue(`--${имя}`).trim();
        const n = parseInt(hex.slice(1), 16);
        return `rgb(${(n >> 16) & 255}, ${(n >> 8) & 255}, ${n & 255})`;
      };
      /* Цена, телефон и вилка: всё, внутри чего есть пробел, плюс, дефис вилки
         или знак валюты. Чистым цифрам (404, номер шага) хватает изоляции. */
      const ОПАСНО = /₪|\+\d|\d[\s ]\d|\d\s*[–—-]\s*\d/;

      const зазор = (a, b) => {
        const dx = Math.max(a.left - b.right, b.left - a.right, 0);
        const dy = Math.max(a.top - b.bottom, b.top - a.bottom, 0);
        return Math.hypot(dx, dy);
      };

      for (const кр of document.querySelectorAll('article.кр')) {
        const холст = кр.getBoundingClientRect();
        const id = кр.id;
        креативы.push({
          id,
          формат: кр.dataset.формат,
          макет: кр.dataset.макет,
          код: кр.dataset.код,
          язык: кр.getAttribute('lang'),
          rtl: кр.getAttribute('dir') === 'rtl',
        });

        /* 8. Холст ровно того размера, который объявлен. */
        const [ш, в] = (кр.dataset.формат ?? '').split('x').map(Number);
        if (Math.abs(холст.width - ш) > 0.5 || Math.abs(холст.height - в) > 0.5) {
          беды.push(
            `${id}: холст ${Math.round(холст.width)}×${Math.round(холст.height)}, объявлено ${кр.dataset.формат}`,
          );
        }

        /* 3. Каждый текст несёт ключ обещания. Ключ ищется вверх по дереву:
           `<b>` внутри помеченного абзаца — часть той же строки, а не новая. */
        for (const узел of кр.querySelectorAll('*')) {
          const свой_текст = [...узел.childNodes].some(
            (у) => у.nodeType === Node.TEXT_NODE && у.textContent.trim().length > 0,
          );
          if (!свой_текст) continue;
          if (!узел.closest('[data-обещание]')) {
            беды.push(
              `${id}: текст без ключа обещания — «${узел.textContent.trim().slice(0, 40)}»`,
            );
          }
        }

        /* 4. Стоп-слова по отрисованному тексту, а не по разметке: так ловится
           и то, что собралось из двух соседних элементов. */
        const видно = кр.innerText ?? '';
        const текст = видно.toLowerCase();
        for (const слово of СТОП_СЛОВА) {
          if (текст.includes(слово.toLowerCase())) беды.push(`${id}: стоп-слово «${слово}»`);
        }
        /*
         * Капс имени бренда — отдельная проверка, потому что она единственная
         * чувствительна к регистру, а остальной список нет. Капс `FIXLI` отменён
         * решением 2026-08-10, и воскресить его проще всего случайно: `надпись`
         * набрана `text-transform: uppercase`, и слово «Fixli» внутри неё молча
         * становится «FIXLI». Так и вышло в первой сборке трёх макетов найма.
         * `innerText` отдаёт текст уже преобразованным — то есть ловится ровно
         * то, что увидит человек, а не то, что написано в разметке.
         */
        if (видно.includes('FIXLI')) {
          беды.push(`${id}: «FIXLI» капсом — капс имени бренда отменён 2026-08-10`);
        }

        /*
         * 5а. `dir="ltr"` ставится на строчный элемент, а не на блочный.
         *
         * Атрибут задаёт не только порядок символов, но и базовое направление
         * абзаца, а от него зависит выравнивание. Строка адреса сайта в
         * ивритском креативе приехала абзацем с `dir="ltr"` — и прижалась к
         * левому краю, пока телефон над ней стоял у правого. Замеры молчали
         * (порядок символов верный), нашли глаза. Лечится оборачиванием текста
         * в `<span dir="ltr">` — тем же приёмом, каким уже набран телефон.
         */
        if (кр.getAttribute('dir') === 'rtl') {
          for (const узел of кр.querySelectorAll('[dir="ltr"]')) {
            if (getComputedStyle(узел).display.startsWith('inline')) continue;
            /* Внутри flex и grid положение задаёт раскладка, а не `text-align`,
               и `dir` там ничего не переворачивает. Заодно снимает ложное
               срабатывание на строчных элементах: дети flex-контейнера
               приводятся к блочным. Та же оговорка стоит в сборке печати —
               одно правило обязано быть написано одинаково в обоих местах. */
            const раскладка = узел.parentElement
              ? getComputedStyle(узел.parentElement).display
              : '';
            if (раскладка.includes('flex') || раскладка.includes('grid')) continue;
            беды.push(
              `${id}: dir="ltr" на блочном «${узел.className || узел.tagName}» — он же переключает выравнивание; оберни текст в <span dir="ltr">`,
            );
          }
        }

        /* 5. Bidi: в ивритском креативе цена и телефон обязаны нести dir="ltr". */
        if (кр.getAttribute('dir') === 'rtl') {
          const ходок = document.createTreeWalker(кр, NodeFilter.SHOW_TEXT);
          for (let у = ходок.nextNode(); у; у = ходок.nextNode()) {
            const значение = у.textContent.trim();
            if (!ОПАСНО.test(значение)) continue;
            const носитель = у.parentElement?.closest('[dir]');
            if (!носитель || носитель.getAttribute('dir') !== 'ltr') {
              беды.push(`${id}: «${значение.slice(0, 30)}» без dir="ltr" в ивритском креативе`);
            }
          }
        }

        /* 9. Цвет слоя — тот, который ему назначен таблицей выше. */
        const тёмный = кр.classList.contains('кр--тёмный');
        for (const [селектор, светлый, наТёмном] of ЦВЕТА_СЛОЁВ) {
          const ждём = токен(тёмный ? наТёмном : светлый);
          for (const узел of кр.querySelectorAll(селектор)) {
            const вышло = getComputedStyle(узел).color;
            if (вышло !== ждём) {
              беды.push(`${id}: «${селектор}» окрашен ${вышло}, а должен ${ждём}`);
            }
          }
        }

        /*
         * 10. Ничего не переливается за холст и не заходит в поле креатива.
         *
         * Холст фиксированный, а текст приходит из реестра и может стать
         * длиннее: тогда содержимое не «переполняет» макет заметно, а тихо
         * выдавливает футер за нижнюю кромку. Ровно это и было найдено на
         * `01-переезд-ru` — 23 px перелива при всех девяти зелёных правилах и
         * при картинке, на которой глаз ничего не замечает.
         *
         * Поле берётся из самого макета (`padding`), а не задаётся числом: у
         * сторис снизу 260 px служебной полосы площадки, и цифра «80» здесь
         * означала бы разрешение писать под строкой ответа.
         *
         * Меряются только элементы с ключом обещания, то есть текст. Первая
         * версия правила считала перелив по `scrollHeight` и обвинила восемь
         * креативов сразу — ровно на 36 px каждый: это марка, уходящая за
         * нижнюю кромку навылет, как юбка кузова на борту фургона
         * (`--fx-ad-mark-bleed`). Декоративный вылет — решение, а не дефект,
         * и правило, запрещающее его, учило бы отключать правило.
         */
        const п = getComputedStyle(кр);
        const поле = {
          top: холст.top + parseFloat(п.paddingTop),
          bottom: холст.bottom - parseFloat(п.paddingBottom),
          left: холст.left + parseFloat(п.paddingLeft),
          right: холст.right - parseFloat(п.paddingRight),
        };
        for (const узел of кр.querySelectorAll('[data-обещание]')) {
          const r = узел.getBoundingClientRect();
          const за = [
            r.top + 0.5 < поле.top && 'сверху',
            r.bottom - 0.5 > поле.bottom && 'снизу',
            r.left + 0.5 < поле.left && 'от начала',
            r.right - 0.5 > поле.right && 'от конца',
          ].filter(Boolean);
          if (за.length) {
            беды.push(`${id}: «${узел.dataset.обещание}» заходит в поле креатива (${за.join(', ')})`);
          }
        }

        /*
         * 11–13. Фотография в креативе.
         *
         * Типографический макет врёт словами, и их стерегут правила 3 и 4.
         * Фотография врёт тремя своими способами, и каждый ниже.
         */
        for (const снимок of кр.querySelectorAll('.кр-снимок')) {
          const src = снимок.getAttribute('src');

          /* 11. Кадр — только из списка разрешённых. Файл, попавший в креатив,
             уходит в рекламный кабинет; согласие человека в кадре кодом не
             проверить, поэтому проверяется то, что можно: сам факт, что этот
             кадр внесён в список руками и с основанием. */
          if (!КАДРЫ.includes(src)) {
            беды.push(`${id}: кадр «${src}» не в списке разрешённых — см. РАЗРЕШЁННЫЕ_КАДРЫ`);
          }

          if (!снимок.complete || снимок.naturalWidth === 0) {
            беды.push(`${id}: кадр не отрисовался — ${src}`);
            continue;
          }

          /* 12. Кроп задан файлом, а не браузером. Файл лежит ровно в пропорции
             своего холста, и `object-fit: cover` ничего не режет. Разойдись они
             — обрезку начнёт делать вёрстка, и «что видно на креативе» станет
             следствием отступа в CSS, а не данных в git. Прошлая сессия уже
             платила за это: кадр после кропа перестал показывать вещь, о которой
             говорит подпись. */
          const п_файла = снимок.naturalWidth / снимок.naturalHeight;
          const п_холста = холст.width / холст.height;
          if (Math.abs(п_файла - п_холста) / п_холста > 0.01) {
            беды.push(
              `${id}: кадр ${снимок.naturalWidth}×${снимок.naturalHeight} (${п_файла.toFixed(3)}) не в пропорции холста ${п_холста.toFixed(3)} — cover срежет его молча`,
            );
          }

          /* Увеличение: материал снят телефоном и пришёл через мессенджер. За
             полутора разами начинается мыло, и креатив выглядит дешевле работы,
             которую показывает. Тот же предел стоит в `подготовить-кадры.mjs` —
             здесь он проверяется по тому, что реально отрисовано. */
          if (холст.width / снимок.naturalWidth > 1.01) {
            беды.push(
              `${id}: кадр ${снимок.naturalWidth} px растягивается до ${Math.round(холст.width)} px — готовь файл в размер холста`,
            );
          }
        }

        /* 13. На фотомакете текст стоит на сплошной подложке.
           Контраст к фотографии посчитать нельзя — он свой в каждой точке
           кадра, — поэтому правило 9 (цвет слоя равен токену) на снимке ничего
           не гарантирует. Гарантирует непрозрачная плита под текстом: пара
           «белое на тёмно-синем» стоит в таблице контрастов бренда. */
        if (кр.classList.contains('кр--снимок')) {
          for (const узел of кр.querySelectorAll('[data-обещание]')) {
            let фон = null;
            for (let у = узел; у && у !== кр.parentElement; у = у.parentElement) {
              const цвет = getComputedStyle(у).backgroundColor;
              const альфа = цвет.startsWith('rgba') ? Number(цвет.split(',')[3]) : 1;
              if (цвет !== 'transparent' && альфа === 1) {
                фон = { узел: у, цвет };
                break;
              }
            }
            if (!фон || фон.узел === кр) {
              беды.push(
                `${id}: «${узел.dataset.обещание}» стоит прямо на фотографии — контраст к кадру не проверяем, нужна сплошная плита`,
              );
            }
          }
          for (const плита of кр.querySelectorAll('.кр-плита')) {
            const вышло = getComputedStyle(плита).backgroundColor;
            const ждём = токен('fx-navy-deep');
            if (вышло !== ждём) беды.push(`${id}: плита залита ${вышло}, а должна ${ждём}`);
          }
        }

        /* 6–7. Знак: цел, не зеркален, не мельче порога, с охранным полем. */
        for (const знак of кр.querySelectorAll('.кр-знак')) {
          const r = знак.getBoundingClientRect();
          if (!знак.complete || знак.naturalWidth === 0) {
            беды.push(`${id}: файл знака не отрисовался — ${знак.getAttribute('src')}`);
            continue;
          }
          const т = getComputedStyle(знак).transform;
          if (т !== 'none') беды.push(`${id}: знак трансформирован (${т}) — его не зеркалят`);

          const объявлено =
            Number(знак.getAttribute('width')) / Number(знак.getAttribute('height'));
          const вышло = r.width / r.height;
          if (Math.abs(объявлено - вышло) / объявлено > 0.01) {
            беды.push(
              `${id}: знак растянут — пропорция ${вышло.toFixed(3)} вместо ${объявлено.toFixed(3)}`,
            );
          }
          if (r.width < МИНИМУМ_ЗНАКА) {
            беды.push(`${id}: знак ${Math.round(r.width)} px — мельче порога ${МИНИМУМ_ЗНАКА}`);
          }

          const поле = ОХРАННОЕ_ПОЛЕ * r.height;
          /*
           * Охранное поле отмеряется от того края, за которым для знака
           * кончается «своя» поверхность. На типографическом макете это кромка
           * холста, а на фотомакете — край плиты: за ним начинается снимок, и
           * знак, прижатый к нему, нарушает раздел 01 ровно так же.
           *
           * Правило расширено 2026-08-27 по замеру: в квадрате знак стоял
           * в 16 px от края плиты при норме 22,9, а прежняя проверка молчала —
           * до кромки холста там 96 px. Нашли глаза на ивритском PNG, замер
           * показал, что дефект в обеих локалях.
           */
          const плита = знак.closest('.кр-плита');
          const рамка = плита ? плита.getBoundingClientRect() : холст;
          const до_кромок = Math.min(
            r.top - рамка.top,
            рамка.bottom - r.bottom,
            r.left - рамка.left,
            рамка.right - r.right,
          );
          if (до_кромок + 0.5 < поле) {
            беды.push(
              `${id}: охранное поле ${до_кромок.toFixed(1)} px при норме ${поле.toFixed(1)}`,
            );
          }
          for (const сосед of кр.querySelectorAll('[data-обещание]')) {
            if (сосед.contains(знак)) continue;
            const д = зазор(r, сосед.getBoundingClientRect());
            if (д + 0.5 < поле) {
              беды.push(
                `${id}: знак ближе охранного поля к тексту — ${д.toFixed(1)} px при норме ${поле.toFixed(1)}`,
              );
            }
          }
        }
      }
      return { беды, креативы };
    },
    { ОХРАННОЕ_ПОЛЕ, МИНИМУМ_ЗНАКА, СТОП_СЛОВА, ЦВЕТА_СЛОЁВ, КАДРЫ: [...РАЗРЕШЁННЫЕ_КАДРЫ.keys()] },
  );

  /* 3. Ключи — против реестра. Проверяется в Node: реестр читается с диска. */
  const ключи = await стр.$$eval('article.кр [data-обещание]', (узлы) =>
    узлы.map((у) => ({ id: у.closest('article.кр').id, ключ: у.dataset.обещание })),
  );
  const бедыКлючей = [];
  for (const { id, ключ } of ключи) {
    const статус = реестр.get(ключ);
    if (!статус) бедыКлючей.push(`${id}: ключа «${ключ}» нет в реестре обещаний`);
    else if (статус === 'запрет') бедыКлючей.push(`${id}: ключ «${ключ}» помечен в реестре 🔴`);
  }

  /*
   * Коды объявлений уникальны. Код — единственное, чем в отчёте по источникам
   * отличается одно объявление от другого: два макета с одним кодом сольются
   * в одну строку, и решение «какое работает» будет принято по неверным
   * числам. Вводятся коды руками, поэтому дубль здесь — вопрос времени.
   * Прочерк у шаблона и аватара законен: у них нет ни текста, ни размещения.
   */
  const бедыКодов = [];
  const поКоду = new Map();
  for (const к of проверка.креативы) {
    if (!к.код || к.код === '—') continue;
    if (поКоду.has(к.код)) бедыКодов.push(`${к.id}: код «${к.код}» уже занят макетом ${поКоду.get(к.код)}`);
    else поКоду.set(к.код, к.id);
  }

  /* Парность локалей. */
  const бедыПар = [];
  const поId = new Map(проверка.креативы.map((к) => [к.id, к]));
  for (const к of проверка.креативы) {
    if (!к.id.endsWith('-ru')) continue;
    const пара = поId.get(`${к.id.slice(0, -3)}-he`);
    if (!пара) бедыПар.push(`${к.id}: нет ивритской версии`);
    else if (пара.макет !== к.макет || пара.формат !== к.формат) {
      бедыПар.push(`${к.id}: ивритская версия разошлась по макету или формату`);
    }
  }

  const всё = [...проверка.беды, ...new Set(бедыКлючей), ...бедыКодов, ...бедыПар];
  if (всё.length) {
    console.error(`Экспорт не начат: ${всё.length} нарушений\n`);
    for (const беда of всё) console.error(`  • ${беда}`);
    await браузер.close();
    process.exit(1);
  }

  /* ─── PNG ──────────────────────────────────────────────────────────────── */

  rmSync(выход, { recursive: true, force: true });
  mkdirSync(выход, { recursive: true });
  /* Иврит уезжает в отдельную папку, а не просто в файл с суффиксом: тексты
     не вычитаны носителем, и человек, открывший папку за файлом для кабинета,
     обязан споткнуться о название, а не прочитать его в описи. */
  const ивритская = join(выход, 'иврит-до-вычитки');
  mkdirSync(ивритская, { recursive: true });

  const опись = [];
  for (const к of проверка.креативы) {
    const папка = к.id.endsWith('-he') ? ивритская : выход;
    const файл = join(папка, `${к.id}.png`);
    await стр.locator(`article[id="${к.id}"]`).screenshot({ path: файл });
    опись.push(`${к.id}.png — ${к.формат}, макет «${к.макет}», метка ${к.код}`);
    console.log(`  ${к.id} — ${к.формат}`);
  }

  writeFileSync(
    join(выход, 'опись.txt'),
    [
      'Рекламные креативы Fixli — собрано node brand/kit/ads/собрать.mjs',
      'Правится не PNG, а креативы.html: PNG пересобираются одной командой.',
      'Ивритские версии лежат в иврит-до-вычитки/ и до вычитки носителем не публикуются.',
      '',
      ...опись,
    ].join('\n'),
    'utf8',
  );

  console.log(`\nКреативов собрано: ${проверка.креативы.length} → ${выход}`);
  console.log('Все тринадцать правил пройдены, ключи обещаний сверены с реестром.');
} finally {
  await браузер.close();
}
