/* ─── Реестр обещаний: ключ → статус ─────────────────────────────────────── */

/**
 * Реестр — обычный markdown, который читает человек. Ключи вынимаются по
 * колонке с обратными кавычками, статус — по эмодзи в заголовке раздела, под
 * которым строка стоит. Отдельного машинного формата заводить не стали: два
 * файла с одним содержанием разъезжаются, а человек читает тот, что красивее.
 */
function прочитать_реестр() {
  const строки = readFileSync(РЕЕСТР, 'utf8').split('\n');
  const ключи = new Map();
  let статус = null;
  for (const строка of строки) {
    if (строка.startsWith('## ')) {
      if (строка.includes('✅')) статус = 'ok';
      else if (строка.includes('🟡')) статус = 'оговорка';
      else if (строка.includes('🔴')) статус = 'запрет';
      else статус = null;
      continue;
    }
    if (!статус || !строка.startsWith('| `')) continue;
    const ключ = строка.match(/^\|\s*`([^`]+)`/);
    if (ключ) ключи.set(ключ[1], статус);
  }
  return ключи;
}

/* ─── Ассерты по исходникам ──────────────────────────────────────────────── */

const беды = [];

/* Тела комментариев затираются пробелами, переводы строк остаются: номера строк
   в отчёте остаются настоящими, а замер цвета, записанный словами, не считается
   нарушением — именно так устроен весь tokens.css. */
const затереть = (m) => m.replace(/[^\n]/g, ' ');
const ФИЗИЧЕСКИЕ =
  /(?:^|[;{\s])(?:margin|padding|border|inset)-(?:left|right)\b|(?:^|[;{\s])(?:left|right)\s*:|text-align\s*:\s*(?:left|right)\b|float\s*:\s*(?:left|right)\b/;

for (const путь of [СТИЛИ, СТРАНИЦА]) {
  const исходник = readFileSync(путь, 'utf8');
  const имя = путь.slice(ЗДЕСЬ.length + 1);
  const код = исходник.replace(/\/\*[\s\S]*?\*\//g, затереть).replace(/<!--[\s\S]*?-->/g, затереть);
  код.split('\n').forEach((строка, i) => {
    if (строка.includes('data:image/svg+xml')) return;
    const цвет = строка.match(/#[0-9a-fA-F]{3,8}\b|\brgba?\(|\bhsla?\(/);
    if (цвет) беды.push(`${имя}:${i + 1} — литерал цвета «${цвет[0]}»`);
    const физ = строка.match(ФИЗИЧЕСКИЕ);
    if (физ) беды.push(`${имя}:${i + 1} — физическое свойство «${физ[0].trim()}»`);
  });
}

