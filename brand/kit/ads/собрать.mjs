/**
 * Сборка рекламных креативов Fixli: HTML → PNG ровно тех размеров, которых
 * просит площадка.
 *
 * Зачем скрипт, а не экспорт из редактора: креатив меняется чаще, чем делается.
 * Правка цены, номера или формулировки — это правка одной строки в
 * `креативы.html` и одна команда, а не заход в макет, где текст лежит слоем и
 * может разойтись с тем, что компания на самом деле обещает.
 *
 * ── Что проверяется ПЕРЕД съёмкой ────────────────────────────────────────
 * Десять правил. Первые два — общие для всех носителей бренда, остальные —
 * появились из-за того, что креатив уходит наружу и врёт дороже, чем страница:
 *
 *  1. литерал цвета в CSS — значение живёт один раз, в `brand/tokens.css`;
 *  2. физическое свойство вместо логического — каждый креатив существует и
 *     справа налево;
 *  3. обещания: каждый текст несёт ключ `data-обещание`, каждый ключ есть в
 *     `реестр-обещаний.md` и не помечен там красным;
 *  4. стоп-слова в отрисованном тексте — страховка, гарантия, 24/7, скидка;
 *  5. bidi: цена и телефон в ивритском креативе обязаны иметь `dir="ltr"`,
 *     иначе `+972 55-2947783` читается как «55-2947783 +972»;
 *  6. знак: не зеркалится, не растянут, не мельче порога из раздела 01;
 *  7. охранное поле знака — не меньше одного диаметра головы, 0,21 его высоты;
 *  8. размер холста совпадает с объявленным в `data-формат`;
 *  9. цвет каждого слоя равен назначенному ему токену;
 * 10. ни один текст не заходит в поле креатива.
 *
 * Десятое правило написано этой же работой и в ней же сработало. Строка адреса
 * сайта встала в футер — и замер показал, что на `01-переезд-ru` содержимое
 * переливается за холст на 23 px: русский заголовок идёт в три строки, триада
 * в футере тоже (в иврите та же триада укладывается в одну). Перелив был там и
 * до строки адреса, но не был виден: контакт стоял одной строкой и
 * центрировался внутри высокого футера. Девять правил молчали, глаза на PNG —
 * тоже. Тот же класс, что «титры молча ушли четвёртой строкой» в карточке
 * ссылки: холст фиксирован, а текст приходит из реестра и может вырасти.
 *
 * Девятое правило появилось не из головы: первая сборка отдала креативы, в
 * которых оранжевая надпись, цена и телефон были серыми. Значения в токенах
 * были верны, литералов в CSS не было, все восемь проверок молчали — а
 * `.витрина p` со специфичностью (0,1,1) бил `.кр-надпись` (0,1,0) и
 * перекрашивал текст ВНУТРИ креативов. Картинка врала под верными числами;
 * поймали глаза. Теперь ловит сторож.
 *
 * Плюс парность: у каждого русского креатива обязан быть ивритский того же
 * макета. Разошлись — значит одна из локалей тихо отстала.
 *
 * Запуск: node brand/kit/ads/собрать.mjs [папка]
 */
