/**
 * Тексты французских объявлений: разбор документа вычитки и проверка.
 *
 * Зачем отдельный файл. Строки на **макетах** сверяет сборщик кита
 * (правила 16 и 17), а **тела объявлений и заголовок** до 2026-09-13 не
 * проверял никто: они живут в `content/ads/французский-тест.md` и уходят
 * в кабинет скриптом, минуя кит. Между тем в ленте текст читается раньше
 * картинки, а следующая правка этих строк — вычитка носителем, который
 * проверяет язык и не знает реестра обещаний.
 *
 * Кто зовёт:
 *   • `собрать.mjs` — правилом 18, вместе с остальными правилами кита;
 *   • `.business/реклама-api/создать-французскую.mjs` — перед записью в кабинет;
 *   • `apps/site/tests/hi.test.ts` — чтобы падало в гейте CI, а не только
 *     у того, кто вспомнил запустить сборку.
 *
 * Своим ходом:  node brand/kit/ads/французские-объявления.mjs
 */
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { СТОП_СЛОВА } from './стоп-слова.mjs';

export const ДОКУМЕНТ = fileURLToPath(
  new URL('../../../content/ads/французский-тест.md', import.meta.url),
);

/**
 * Заголовок и три тела — ровно те строки, которые скрипт создания отправляет
 * в Meta. Разбор повторяет разбор скрипта намеренно: если они разойдутся,
 * проверка будет смотреть не на то, что уезжает в кабинет.
 */
export function прочитать_объявления(путь = ДОКУМЕНТ) {
  const текст = readFileSync(путь, 'utf8');
  const заголовок = /\*\*Заголовок, один на все три:\*\*\s*\n\s*\n> (.+)/.exec(текст)?.[1]?.trim();
  const тела = new Map();
  for (const m of текст.matchAll(/^### (\d{2}) — .*\n([\s\S]*?)(?=\n### |\n\*\*Кнопка)/gm)) {
    const тело = m[2]
      .split('\n')
      .filter((l) => l.startsWith('>'))
      .map((l) => l.replace(/^>\s?/, '').trimEnd())
      .join('\n')
      .replace(/\n{3,}/g, '\n\n')
      .trim();
    тела.set(m[1], тело);
  }
  return { заголовок, тела };
}

/**
 * Знаки, перед которыми французская типографика просит пробел, и он обязан
 * быть неразрывным: обычный разрешает браузеру оторвать знак от фразы.
 *
 * Узкий неразрывный U+202F, которого просит строгая норма, ЗАПРЕЩЁН — в Rubik
 * этого глифа нет, и он рисуется нулевой шириной (поймано глазами на карточке
 * ссылки сайта: «1000» вместо «1 000» при верной строке в словаре).
 */
const ЗНАКИ_С_ПРОБЕЛОМ = /[  ][:;!?%]/;

/** Проверяет один текст. Возвращает список бед — пустой, если всё чисто. */
export function проверить_текст(адрес, текст) {
  const беды = [];
  const низ = текст.toLowerCase();

  for (const слово of СТОП_СЛОВА) {
    if (низ.includes(слово.toLowerCase())) {
      беды.push(`${адрес}: запрещённое слово «${слово}» — реестр обещаний ставит на нём 🔴`);
    }
  }
  if (ЗНАКИ_С_ПРОБЕЛОМ.test(текст)) {
    беды.push(`${адрес}: обычный пробел перед знаком — нужен неразрывный U+00A0`);
  }
  if (/« | »/.test(текст)) беды.push(`${адрес}: кавычка отрывается от слова — нужен U+00A0`);
  if (текст.includes(' ')) беды.push(`${адрес}: U+202F не рисуется этим шрифтом — замени на U+00A0`);
  if (/\w'\w/.test(текст)) беды.push(`${адрес}: прямой апостроф вместо типографского ’`);
  if (/\d \d{3}\b/.test(текст)) беды.push(`${адрес}: разряд числа обычным пробелом — нужен U+00A0`);
  /* Число и знак валюты — такая же неразрывная пара, как разряд. Дыру нашла
     диверсия 2026-09-13: «500 ₪» с обычным пробелом проходило зелёным, а на
     границе строки это «500» в конце одной строки и «₪» в начале следующей. */
  if (/\d ?₪/.test(текст) && !/\d\u00a0₪/.test(текст)) {
    беды.push(`${адрес}: «₪» отрывается от числа — нужен U+00A0 между ними`);
  }
  return беды;
}

/**
 * Все тексты сразу. Отдельно считает неразрывные пробелы: **Meta снимает их
 * при записи** — проверено 2026-09-13 чтением объявления и предпросмотром
 * `MOBILE_FEED_STANDARD`, где стоит «1 000» с обычным пробелом. Это не наша
 * ошибка и кодом не лечится, но знать про это обязан тот, кто решает, как
 * записать число в ленте.
 */
export function проверить_объявления(путь = ДОКУМЕНТ) {
  const { заголовок, тела } = прочитать_объявления(путь);
  const беды = [];
  if (!заголовок) беды.push('заголовок объявлений не разобран — сверять нечего');
  if (тела.size !== 3) беды.push(`тел объявлений ${тела.size}, ждали три`);

  const пары = [['заголовок', заголовок ?? ''], ...[...тела].map(([н, т]) => [`тело ${н}`, т])];
  for (const [адрес, текст] of пары) беды.push(...проверить_текст(адрес, текст));

  /*
   * Что человек прочитает в ленте, не нажимая «ещё».
   *
   * Facebook показывает около трёх строк, и перевод строки обрывает показ
   * раньше лимита. Снято с предпросмотра `MOBILE_FEED_STANDARD` 2026-09-13:
   * у объявления 02 видимая часть кончалась двоеточием — перечисление было
   * обещано и не показано. Перенос там стоял не по смыслу, а по ширине
   * markdown-строки, и в кабинет уехал настоящим `\n`.
   *
   * Поэтому правило про ПЕРВУЮ строку: она обязана быть законченной мыслью.
   * Переносы внутри следующих абзацев законны — так набраны и русские
   * объявления, там два коротких утверждения стоят столбиком.
   */
  for (const [адрес, текст] of пары.slice(1)) {
    const первая = текст.split('\n')[0].trimEnd();
    if (/[:;,—-]$/.test(первая)) {
      беды.push(
        `${адрес}: видимая в ленте строка кончается на «${первая.slice(-1)}» — ` +
          'обещает продолжение, которого человек не увидит без нажатия',
      );
    }
  }

  const неразрывных = пары.reduce((s, [, т]) => s + (т.match(/ /g) ?? []).length, 0);
  return { беды, неразрывных, заголовок, тела };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const { беды, неразрывных, заголовок, тела } = проверить_объявления();
  if (беды.length) {
    console.error(`Французские объявления: ${беды.length} нарушений\n`);
    for (const б of беды) console.error(`  • ${б}`);
    process.exit(1);
  }
  console.log(`Заголовок (${заголовок.length} зн.): ${заголовок}`);
  for (const [н, т] of тела) console.log(`Тело ${н}: ${т.length} зн.`);
  console.log(`\nЧисто. Неразрывных пробелов в текстах: ${неразрывных} — Meta снимет их при записи.`);
}
