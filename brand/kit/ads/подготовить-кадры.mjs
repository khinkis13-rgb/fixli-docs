/**
 * Подготовка фотографий для рекламных креативов.
 *
 * Кроп задаётся здесь, а не в CSS, и это решение с причиной. `object-fit: cover`
 * режет кадр по пропорции холста в момент отрисовки — то есть «что видно на
 * креативе» становится следствием вёрстки, а не файла, лежащего в git. Тогда
 * правка отступа в макете молча меняет содержание фотографии, и заметить это
 * можно только глазами на PNG. Здесь кроп — часть данных: он записан числами,
 * виден в diff и повторяется командой.
 *
 * Прошлая сессия дала правило, стоившее хода: **кандидата смотрят после кропа,
 * а не до.** Лучший по резкости кадр после обрезки 3:4 перестал показывать
 * собранную вещь — кроп меняет не качество, а содержание. Поэтому у каждого
 * окна ниже стоит строка «что в кадре остаётся».
 *
 * Исходники лежат в `.business/фото-работ/`, а она **вне git**: скрипт работает
 * у того, у кого есть материал заказчика. Результат (`фото/*.webp`) в git есть —
 * это и делает креативы воспроизводимыми без доступа к поставке.
 *
 * Запуск: `node brand/kit/ads/подготовить-кадры.mjs`
 */

import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ЗДЕСЬ = dirname(fileURLToPath(import.meta.url));
const ПОСТАВКА = join(ЗДЕСЬ, '../../../.business/фото-работ/2026-08-26-от-игоря/фото');
const ВЫХОД = join(ЗДЕСЬ, 'фото');

/*
 * Предел увеличения. Материал снят телефоном и пришёл через мессенджер: у
 * главного кадра поставки 720 px по ширине при холсте 1080. Увеличение само по
 * себе информации не добавляет — оно лишь избавляет от второго масштабирования
 * в браузере, — но за некоторой границей начинается мыло, и креатив выглядит
 * дешевле работы, которую показывает. Полтора раза проходят, два — нет.
 */
const ПРЕДЕЛ_УВЕЛИЧЕНИЯ = 1.6;

/**
 * Каждое окно кропа объясняет само себя: почему такое смещение и что в кадре
 * после него остаётся. Список разрешённых к публикации кадров — в описи
 * поставки (`.business/фото-работ/2026-08-26-от-игоря/README.md`), и он же
 * продублирован утверждением в `собрать.mjs`: там проверяется, что креатив не
 * взял кадр мимо этого списка.
 */
const КАДРЫ = [
  {
    имя: 'упаковка-4x5.webp',
    исходник: '192.jpg',
    холст: [1080, 1350],
    окно: [720, 900, 0, 190],
    что: 'четыре предмета в одеялах, стрейч поверх, пол под ними; срезан верх дальнего столба и тёмная витрина над ним',
  },
  {
    имя: 'упаковка-9x16.webp',
    исходник: '192.jpg',
    холст: [1080, 1920],
    окно: null,
    что: 'тот же кадр целиком — он нативно 9:16 (720 × 1280), сторис не кропается вовсе',
  },
  {
    имя: 'телевизор-1x1.webp',
    исходник: '175.jpg',
    холст: [1080, 1080],
    окно: [830, 830, 65, 0],
    что: 'телевизор на стене, полки-соты и верх подвесного комода; сверху 270 px чистой стены из исходника — это 32,5 % кадра, ровно под плиту с текстом (замер строк: объекты начинаются с 270-й). Книги на журнальном столике срезаны намеренно — чужой бренд крупными буквами на креативе читается как случайность',
  },
];

/* Бинари зовутся по имени через PATH — так делает весь остальной проект
   (`.business/видео/`, сборки печати). Абсолютный `/usr/local/bin/…` работал бы
   только на этой машине: у Homebrew на Apple Silicon префикс другой. */
const ешь = (файл, аргументы) => {
  try {
    return execFileSync(файл, аргументы, { stdio: ['ignore', 'pipe', 'pipe'] });
  } catch (ошибка) {
    if (ошибка.code === 'ENOENT') {
      console.error(`Нет инструмента «${файл}» в PATH. Нужны ffmpeg (с ffprobe) и cwebp.`);
      process.exit(1);
    }
    throw ошибка;
  }
};

if (!existsSync(ПОСТАВКА)) {
  console.error(`Нет поставки: ${ПОСТАВКА}`);
  console.error('Кадры лежат в .business/, которая вне git. Готовые webp уже собраны в фото/.');
  process.exit(1);
}

rmSync(ВЫХОД, { recursive: true, force: true });
mkdirSync(ВЫХОД, { recursive: true });

const опись = [
  '# Кадры рекламных креативов',
  '',
  'Собрано `node brand/kit/ads/подготовить-кадры.mjs`. Руками не правится: правка',
  'исчезнет при следующей сборке, а окно кропа в скрипте останется врать.',
  '',
  '| Файл | Исходник | Окно кропа | Увеличение | Что в кадре |',
  '|---|---|---|---|---|',
];

for (const кадр of КАДРЫ) {
  const источник = join(ПОСТАВКА, кадр.исходник);
  if (!existsSync(источник)) {
    console.error(`Нет исходника: ${кадр.исходник}`);
    process.exit(1);
  }

  const [хш, хв] = кадр.холст;
  const фильтры = [];
  if (кадр.окно) {
    const [ш, в, x, y] = кадр.окно;
    /* Пропорция окна обязана совпасть с пропорцией холста: иначе разницу
       доберёт `object-fit` в браузере, и кроп снова станет невидимым. */
    const расхождение = Math.abs(ш / в - хш / хв) / (хш / хв);
    if (расхождение > 0.005) {
      console.error(
        `${кадр.имя}: окно ${ш}×${в} (${(ш / в).toFixed(3)}) не в пропорции холста ${хш}×${хв} (${(хш / хв).toFixed(3)})`,
      );
      process.exit(1);
    }
    фильтры.push(`crop=${ш}:${в}:${x}:${y}`);
  }
  фильтры.push(`scale=${хш}:${хв}:flags=lanczos`);

  const исходныйРазмер = ешь('ffprobe', [
    '-v', 'error', '-select_streams', 'v:0',
    '-show_entries', 'stream=width,height', '-of', 'csv=p=0:s=x',
    источник,
  ]).toString().trim();
  const [иш] = исходныйРазмер.split('x').map(Number);
  const ширинаОкна = кадр.окно ? кадр.окно[0] : иш;
  const увеличение = хш / ширинаОкна;
  if (увеличение > ПРЕДЕЛ_УВЕЛИЧЕНИЯ) {
    console.error(
      `${кадр.имя}: увеличение ×${увеличение.toFixed(2)} при пределе ×${ПРЕДЕЛ_УВЕЛИЧЕНИЯ} — кадр станет мылом`,
    );
    process.exit(1);
  }

  const png = join(ВЫХОД, `${кадр.имя}.png`);
  ешь('ffmpeg', ['-y', '-loglevel', 'error', '-i', источник, '-vf', фильтры.join(','), png]);
  ешь('cwebp', ['-q', '82', '-quiet', png, '-o', join(ВЫХОД, кадр.имя)]);
  rmSync(png);

  опись.push(
    `| \`${кадр.имя}\` | \`${кадр.исходник}\` (${исходныйРазмер}) | ${кадр.окно ? кадр.окно.join(' · ') : 'без кропа'} | ×${увеличение.toFixed(2)} | ${кадр.что} |`,
  );
  console.log(`${кадр.имя} — ${хш}×${хв}, увеличение ×${увеличение.toFixed(2)}`);
}

опись.push(
  '',
  '**Ни на одном кадре нет людей, документов, номеров квартир и чужих логотипов** —',
  'это условие публикации, а не совпадение. Кадры, где видно лицо работника',
  '(`194`, `197`, `видео/189`, `190`), ждут его разрешения и в креативы не идут;',
  'видеоотзыв клиентки ждёт её разрешения. Список разрешённого — в описи поставки',
  '`.business/фото-работ/2026-08-26-от-игоря/README.md`, и `собрать.mjs` проверяет',
  'по нему каждый кадр, попавший в креатив.',
  '',
);
writeFileSync(join(ВЫХОД, 'опись.md'), опись.join('\n'), 'utf8');
console.log(`\nГотово: ${КАДРЫ.length} кадра в ${ВЫХОД.slice(ЗДЕСЬ.length + 1)}/`);
